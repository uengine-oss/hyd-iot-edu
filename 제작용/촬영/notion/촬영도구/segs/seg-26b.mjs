 await c.source('N09-06',()=>c.key('Shift+Enter'));
 await c.source('N09-07',()=>c.type('한 페이지에서 시작해 내용이 쌓이면 하위 페이지로 이어 갑니다.'));
 return 'Home gallery and first topic created';
