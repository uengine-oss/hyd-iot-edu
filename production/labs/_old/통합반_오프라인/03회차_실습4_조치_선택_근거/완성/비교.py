class 멈춤(Exception):
    """추측하지 않고 멈춰야 하는 경우."""


def 수_읽기(값):
    """JSON에서 읽은 값을 반올림 없는 수로 바꾼다. 숫자가 아니면 None."""
    if isinstance(값, bool):
        return None
    if isinstance(값, int):
        return Fraction(값)
    if isinstance(값, Decimal) and 값.is_finite():
        return Fraction(값)
    return None


def 글_수_읽기(글):
    try:
        수 = Decimal(글)
    except InvalidOperation:
        return None
    return Fraction(수) if 수.is_finite() else None


def json_읽기(경로):
    with open(경로, encoding="utf-8") as 파일:
        # 소수는 반올림 없이 계산하려고 Decimal로 읽는다. NaN 같은 것은 글자로 남겨 숫자로 치지 않는다.
        return json.load(파일, parse_float=Decimal, parse_constant=lambda 글: 글)


def 업무_값_읽기():
    자료 = json_읽기(업무_값_경로)
    if not isinstance(자료, dict):
        raise 멈춤(f"{업무_값_이름}의 모양이 다릅니다.")
    값들 = {}
    for 항목 in 자료.get("값") or []:
        if isinstance(항목, dict) and isinstance(항목.get("이름"), str):
            값들[항목["이름"]] = 수_읽기(항목.get("값"))
    표준_작업 = {}
    for 항목 in 자료.get("표준_작업") or []:
        if isinstance(항목, dict) and isinstance(항목.get("작업"), str):
            표준_작업[항목["작업"]] = {
                "정지_시간_h": 수_읽기(항목.get("정지_시간_h")),
                "작업비_만원": 수_읽기(항목.get("작업비_만원")),
            }
    return 값들, 표준_작업


def 후보_설정_읽기():
    with open(후보_설정_경로, encoding="utf-8-sig", newline="") as 파일:
        표 = csv.DictReader(파일)
        없는_열 = [열 for 열 in 필요한_설정_열 if 열 not in (표.fieldnames or [])]
        if 없는_열:
            raise 멈춤(f"{후보_설정_이름}에 열이 없습니다: {', '.join(없는_열)}")
        설정들 = {}
        for 행 in 표:
            칸 = {열: (값 or "").strip() for 열, 값 in 행.items() if isinstance(열, str)}
            if 칸["후보"]:
                설정들[칸["후보"]] = 칸
    return 설정들


def 요청_읽기():
    자료 = json_읽기(요청_경로)
    요청들 = 자료.get("요청") if isinstance(자료, dict) else None
    if not isinstance(요청들, list):
        raise 멈춤(f"{요청_이름}에 '요청' 목록이 없습니다.")
    for 순서, 요청 in enumerate(요청들, start=1):
        if not isinstance(요청, dict) or "번호" not in 요청:
            raise 멈춤(f"{요청_이름}의 {순서}번째 요청에 '번호'가 없습니다.")
        if not isinstance(요청.get("후보"), list):
            raise 멈춤(f"요청 {요청['번호']}에 '후보' 목록이 없습니다.")
    return 요청들


def 판정_결과_읽기():
    자료 = json_읽기(판정_결과_경로)
    if not isinstance(자료, list):
        raise 멈춤(f"{판정_결과_이름}이 요청의 목록이 아닙니다.")
    판정들 = {}
    for 순서, 판정 in enumerate(자료, start=1):
        if not isinstance(판정, dict) or "번호" not in 판정:
            raise 멈춤(f"{판정_결과_이름}의 {순서}번째 항목에 '번호'가 없습니다.")
        if not isinstance(판정.get("남은_후보"), list):
            raise 멈춤(f"{판정_결과_이름}의 {판정['번호']}에 '남은_후보' 목록이 없습니다.")
        판정들[판정["번호"]] = 판정
    return 판정들


def 고르기(없는, *쌍들):
    """(값, 그 값이 온 곳) 쌍에서 값만 꺼낸다. 값이 없으면 온 곳을 없는 목록에 적는다."""
    값들 = []
    for 값, 온_곳 in 쌍들:
        if 값 is None and 온_곳 not in 없는:
            없는.append(온_곳)
        값들.append(값)
    return 값들


def 업무_쌍(업무, 이름):
    return (업무.get(이름), f"{업무_값_이름}의 {이름}")


def 설정_풀기(후보, 행, 표준_작업):
    """후보의 설정 한 행을 식에 쓰는 낱말(팬, 부하, 정지 시간, 작업비, 근본 조치)로 푼다."""
    if 행 is None:
        없음 = (None, f"{후보_설정_이름}의 {후보} 행")
        return {"이름": "", "승인": "", "팬": 없음, "부하": 없음,
                "정지_시간": 없음, "작업비": 없음, "근본_조치": 없음}

    def 설정_수(열, 비어_있을_때):
        글 = 행[열]
        if not 글:
            return (Fraction(비어_있을_때), None)
        return (글_수_읽기(글), f"{후보_설정_이름}의 {후보} {열}(숫자로 읽을 수 없는 값 '{글}')")

    작업 = 행["작업지시"]
    if not 작업:
        정지_시간 = 작업비 = (Fraction(0), None)
    elif 작업 not in 표준_작업:
        정지_시간 = 작업비 = (None, f"{업무_값_이름} 표준_작업의 「{작업}」")
    else:
        정지_시간 = (표준_작업[작업]["정지_시간_h"], f"{업무_값_이름} 표준 작업 「{작업}」의 정지_시간_h")
        작업비 = (표준_작업[작업]["작업비_만원"], f"{업무_값_이름} 표준 작업 「{작업}」의 작업비_만원")

    근본_조치 = {"예": True, "아니오": False}.get(행["근본_조치"])
    return {
        "이름": 행.get("이름", ""),
        "승인": 행["승인"],
        "팬": 설정_수("팬_설정_퍼센트", 정상_팬),
        "부하": 설정_수("부하_설정_퍼센트", 설계_부하),
        "정지_시간": 정지_시간,
        "작업비": 작업비,
        "근본_조치": (근본_조치, f"{후보_설정_이름}의 {후보} 근본_조치(「예」도 「아니오」도 아님)"),
    }


# 네 지표. 값과 함께, 계산하는 데 필요했으나 없던 값의 목록을 돌려준다.

def 비용_계산(업무, 설정, 감점들):
    없는 = []
    작업비, 근본_조치 = 고르기(없는, 설정["작업비"], 설정["근본_조치"])
    고장_위험 = None
    if 근본_조치 is True:
        고장_위험 = Fraction(0)
    elif 근본_조치 is False:
        고장_비용, 기간, 고장_간격 = 고르기(
            없는,
            업무_쌍(업무, "계획_외_고장_비용"),
            업무_쌍(업무, "납기까지_남은_시간"),
            업무_쌍(업무, "평균_고장_간격"),
        )
        if 고장_간격 is not None and 고장_간격 == 0:
            없는.append(f"{업무_값_이름}의 평균_고장_간격(0이라 나눌 수 없음)")
        elif None not in (고장_비용, 기간, 고장_간격):
            고장_위험 = 고장_비용 * min(기간 / 고장_간격, Fraction(1))
    감점_합 = Fraction(0)
    for 항목 in 감점들:
        (금액,) = 고르기(없는, (항목["금액"], f"{판정_결과_이름}의 {항목['규칙']} 감점_만원"))
        if 금액 is not None:
            감점_합 += 금액
    if 없는:
        return None, 없는
    return 작업비 + 고장_위험 + 감점_합, 없는


def 생산_계산(업무, 설정):
    없는 = []
    생산_가치, 기간, 잔량, 생산_수량, 위약금, 부하, 정지_시간 = 고르기(
        없는,
        업무_쌍(업무, "시간당_생산_가치"),
        업무_쌍(업무, "납기까지_남은_시간"),
        업무_쌍(업무, "오더_잔량"),
        업무_쌍(업무, "시간당_생산_수량"),
        업무_쌍(업무, "납기_지연_위약금"),
        설정["부하"],
        설정["정지_시간"],
    )
    if 없는:
        return None, 없는
    부하_비율 = 부하 / 설계_부하
    if 생산_수량 * 부하_비율 == 0:
        return None, ["완료까지 걸리는 시간(시간당_생산_수량 × 부하 비율이 0이라 나눌 수 없음)"]
    생산_감소 = 생산_가치 * (기간 * (1 - 부하_비율) + 정지_시간)
    완료까지 = 정지_시간 + 잔량 / (생산_수량 * 부하_비율)
    지연 = max(완료까지 - 기간, Fraction(0))
    return 생산_감소 + 위약금 * 지연, 없는


def 품질_계산(업무, 유온_쌍):
    없는 = []
    로트_쌍 = 업무_쌍(업무, "고온_로트_수량")
    유온, 로트 = 유온_쌍[0], 로트_쌍[0]
    # 두 조건 가운데 하나라도 맞지 않는 것이 확인되면 나머지 값이 없어도 0이다.
    if (유온 is not None and 유온 < 회복_기준_유온) or (로트 is not None and 로트 <= 0):
        return Fraction(0), 없는
    고르기(없는, 유온_쌍, 로트_쌍)
    if 없는:
        return None, 없는
    불량_확률, 클레임_금액 = 고르기(
        없는, 업무_쌍(업무, "고온_로트_불량_확률"), 업무_쌍(업무, "고온_로트_클레임_금액")
    )
    if 없는:
        return None, 없는
    return 불량_확률 * 클레임_금액, 없는


def 에너지_계산(업무, 설정):
    없는 = []
    팬, 추가_전력, 기간, 단가 = 고르기(
        없는,
        설정["팬"],
        업무_쌍(업무, "팬_최대_추가_전력"),
        업무_쌍(업무, "납기까지_남은_시간"),
        업무_쌍(업무, "전력_단가"),
    )
    if 없는:
        return None, 없는
    return (팬 - 정상_팬) * 추가_전력 / 팬_최대_폭 * 기간 * 단가, 없는


def 반올림(수):
    """소수 둘째 자리까지, 사사오입."""
    부호 = -1 if 수 < 0 else 1
    백배 = abs(수) * 100
    몫 = (2 * 백배.numerator + 백배.denominator) // (2 * 백배.denominator)
    return Decimal(부호 * 몫).scaleb(-2)


def 돈(값):
    return f"{값:.2f}"


def 절차_순서(절차_번호):
    """절차 번호가 빠른 쪽을 앞에 두려고, 번호 속의 숫자는 숫자로 견준다."""
    조각 = [int(글) if 글.isdigit() else 글 for 글 in re.split(r"(\d+)", 절차_번호)]
    return (조각, 절차_번호)


def 부르기(후보):
    return f"{후보['후보']}({후보['이름']})" if 후보["이름"] else 후보["후보"]


def 후보_계산(번호, 절차_번호, 업무, 표준_작업, 설정들, 유온들, 후보_판정):
    설정 = 설정_풀기(절차_번호, 설정들.get(절차_번호), 표준_작업)
    근거 = (후보_판정 or {}).get("근거") or []
    감점들 = [
        {"규칙": 항목.get("규칙"), "금액": 수_읽기(항목.get("감점_만원")), "적힌_값": 항목.get("감점_만원")}
        for 항목 in 근거
        if 항목.get("판정") == 감점 and 항목.get("상태") == 맞음
    ]
    경고들 = [항목 for 항목 in 근거 if 항목.get("판정") == 경고]
    유온_쌍 = (유온들.get(절차_번호), f"{요청_이름}의 {번호} {절차_번호} forecast_ts1")

    계산 = {
        "비용": 비용_계산(업무, 설정, 감점들),
        "생산": 생산_계산(업무, 설정),
        "품질": 품질_계산(업무, 유온_쌍),
        "에너지": 에너지_계산(업무, 설정),
    }
    지표 = {이름: (None if 값 is None else 반올림(값)) for 이름, (값, _) in 계산.items()}
    없는 = {이름: 목록 for 이름, (값, 목록) in 계산.items() if 값 is None}
    # 합계는 표에 적는 값(둘째 자리로 반올림한 값)을 더한다.
    합계 = None if 없는 else sum(지표.values(), Decimal(0))
    return {
        "후보": 절차_번호,
        "이름": 설정["이름"],
        "승인": 설정["승인"],
        "지표": 지표,
        "없는": 없는,
        "합계": 합계,
        "순위": None,
        "감점들": 감점들,
        "경고들": 경고들,
    }


def 순위_매기기(후보들):
    매긴 = [후보 for 후보 in 후보들 if 후보["합계"] is not None]
    매긴.sort(key=lambda 후보: (
        후보["합계"],
        0 if 후보["승인"] == 앞에_두는_승인 else 1,
        절차_순서(후보["후보"]),
    ))
    for 순위, 후보 in enumerate(매긴, start=1):
        후보["순위"] = 순위
    return 매긴


def 제외_까닭(후보_판정):
    까닭 = []
    for 항목 in 후보_판정.get("근거") or []:
        if 항목.get("상태") == 맞음 and 항목.get("판정") == 제외:
            까닭.append(str(항목.get("규칙")))
        elif 항목.get("상태") == 확인되지_않음 and 항목.get("판정") in (제외, 감점):
            까닭.append(f"{항목.get('규칙')} {확인되지_않음}")
    return ", ".join(까닭) or "규칙 번호 없음"


def 견주기_문장(추천, 둘째):
    얻는, 잃는, 같은 = [], [], []
    for 이름 in 지표_이름:
        추천_값, 둘째_값 = 추천["지표"][이름], 둘째["지표"][이름]
        if 추천_값 < 둘째_값:
            얻는.append(f"{이름} {돈(둘째_값 - 추천_값)}만 원(추천 {돈(추천_값)}, 2순위 {돈(둘째_값)})")
        elif 추천_값 > 둘째_값:
            잃는.append(f"{이름} {돈(추천_값 - 둘째_값)}만 원(추천 {돈(추천_값)}, 2순위 {돈(둘째_값)})")
        else:
            같은.append(f"{이름} {돈(추천_값)}")
    문장들 = [
        f"2순위와 견주어 얻는 것(덜 잃는 손실): {', '.join(얻는) or '없음'}.",
        f"잃는 것(더 잃는 손실): {', '.join(잃는) or '없음'}.",
    ]
    if 같은:
        문장들.append(f"값이 같은 지표: {', '.join(같은)}.")
    return 문장들


def 없는_값_문장(후보들):
    문장들 = []
    for 후보 in 후보들:
        if not 후보["없는"]:
            continue
        풀이 = "; ".join(f"{이름} — {', '.join(목록)}" for 이름, 목록 in 후보["없는"].items())
        문장들.append(
            f"{부르기(후보)} 후보는 지표를 계산하는 데 필요한 값이 없어 순위를 매기지 않았고 "
            f"추천에서 뺐다(없는 값: {풀이})."
        )
    return 문장들


def 사유_만들기(판정, 후보들, 매긴):
    if not 후보들:
        문장들 = ["조치 불가: 규칙을 통과해 남은 후보가 없어 추천하지 않는다."]
        제외된 = [
            f"{후보_판정.get('후보')}({제외_까닭(후보_판정)})"
            for 후보_판정 in 판정.get("후보별_판정") or []
            if isinstance(후보_판정, dict) and 후보_판정.get("판정") == 제외
        ]
        if 제외된:
            문장들.append(f"후보마다 제외된 규칙: {', '.join(제외된)}.")
        return " ".join(문장들)

    if not 매긴:
        문장들 = ["순위를 매길 수 있는 후보가 없어 추천하지 않는다."]
        return " ".join(문장들 + 없는_값_문장(후보들))

    추천 = 매긴[0]
    지표_풀이 = ", ".join(f"{이름} {돈(추천['지표'][이름])}" for 이름 in 지표_이름)
    문장들 = [f"{부르기(추천)} 후보를 추천한다."]
    if len(매긴) == 1:
        문장들.append(f"네 지표의 합계는 {돈(추천['합계'])}만 원({지표_풀이})이다.")
        if len(후보들) == 1:
            문장들.append("남은 후보가 이것 하나뿐이어서 견줄 후보가 없었다.")
        else:
            문장들.append("다른 후보는 순위를 매기지 못해 견줄 수 있는 후보가 없었다.")
    else:
        둘째 = 매긴[1]
        문장들.append(
            f"네 지표의 합계는 {돈(추천['합계'])}만 원({지표_풀이})으로 순위를 매긴 후보 가운데 가장 작다."
        )
        순위별 = ", ".join(f"{후보['순위']}순위 {후보['후보']} {돈(후보['합계'])}" for 후보 in 매긴)
        문장들.append(f"순위별 합계(만 원): {순위별}.")
        차이 = 둘째["합계"] - 추천["합계"]
        if 차이 > 0:
            문장들.append(
                f"2순위 {부르기(둘째)} 후보의 합계는 {돈(둘째['합계'])}만 원으로, 추천한 후보가 {돈(차이)}만 원 작다."
            )
        else:
            문장들.append(f"2순위 {부르기(둘째)} 후보의 합계는 {돈(둘째['합계'])}만 원으로 추천한 후보와 같다.")
        문장들.extend(견주기_문장(추천, 둘째))

    더한_감점 = [
        f"{후보['후보']} {항목['규칙']} {항목['적힌_값']}만 원"
        for 후보 in 후보들 if 후보["지표"]["비용"] is not None
        for 항목 in 후보["감점들"]
    ]
    if 더한_감점:
        문장들.append(f"결정표의 감점을 비용에 더한 후보: {', '.join(더한_감점)}.")

    if 추천["경고들"]:
        경고_풀이 = "; ".join(
            f"{항목.get('규칙')}"
            + (f"({확인되지_않음})" if 항목.get("상태") == 확인되지_않음 else "")
            + f" 「{항목.get('원문')}」"
            for 항목 in 추천["경고들"]
        )
        문장들.append(f"추천한 후보에 붙은 경고: {경고_풀이}")
    else:
        문장들.append("추천한 후보에 붙은 경고는 없다.")

    합계별 = {}
    for 후보 in 매긴:
        합계별.setdefault(후보["합계"], []).append(후보["후보"])
    for 합계, 이름들 in 합계별.items():
        if len(이름들) > 1:
            문장들.append(
                f"합계가 {돈(합계)}만 원으로 같은 후보({', '.join(이름들)})는 승인이 {앞에_두는_승인}인 후보를 "
                "앞에, 그래도 같으면 절차 번호가 빠른 쪽을 앞에 두었다."
            )

    문장들.extend(없는_값_문장(후보들))
    return " ".join(문장들)


def 요청_비교(요청, 판정, 업무, 표준_작업, 설정들):
    번호 = 요청["번호"]
    유온들 = {
        후보["sop"]: 수_읽기(후보.get("forecast_ts1"))
        for 후보 in 요청["후보"]
        if isinstance(후보, dict) and isinstance(후보.get("sop"), str)
    }
    후보_판정들 = {
        후보_판정.get("후보"): 후보_판정
        for 후보_판정 in 판정.get("후보별_판정") or []
        if isinstance(후보_판정, dict)
    }
    후보들 = [
        후보_계산(번호, 절차_번호, 업무, 표준_작업, 설정들, 유온들, 후보_판정들.get(절차_번호))
        for 절차_번호 in 판정["남은_후보"]
    ]
    매긴 = 순위_매기기(후보들)
    return {
        "번호": 번호,
        "비교_대상": list(판정["남은_후보"]),
        "후보별_지표": [
            {"후보": 후보["후보"], **{이름: 후보["지표"][이름] for 이름 in 지표_이름}, "순위": 후보["순위"]}
            for 후보 in 후보들
        ],
        "추천": 매긴[0]["후보"] if 매긴 else None,
        "추천_사유": 사유_만들기(판정, 후보들, 매긴),
    }


def json_적기(값, 깊이=0):
    """금액을 0.00처럼 둘째 자리까지 찍으려고 직접 적는다."""
    안, 밖 = "  " * (깊이 + 1), "  " * 깊이
    if 값 is None:
        return "null"
    if isinstance(값, Decimal):
        return 돈(값)
    if isinstance(값, (str, int)):
        return json.dumps(값, ensure_ascii=False)
    if isinstance(값, list):
        if not 값:
            return "[]"
        return "[\n" + ",\n".join(안 + json_적기(항목, 깊이 + 1) for 항목 in 값) + "\n" + 밖 + "]"
    if isinstance(값, dict):
        return "{\n" + ",\n".join(
            안 + json.dumps(이름, ensure_ascii=False) + ": " + json_적기(항목, 깊이 + 1)
            for 이름, 항목 in 값.items()
        ) + "\n" + 밖 + "}"
    raise TypeError(f"JSON으로 적을 수 없는 값입니다: {값!r}")


def 칸에_넣기(글):
    return str(글).replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def 원인_진단_읽기():
    자료 = json_읽기(원인_진단_경로)
    if not isinstance(자료, dict) or not isinstance(자료.get("원인_후보"), list):
        raise 멈춤(f"{원인_진단_이름}에 '원인_후보' 목록이 없습니다.")
    return 자료


def 값_보이기(값, 단위=""):
    if 값 is None:
        return "없음"
    return f"{값} {단위}" if 단위 else str(값)


def 증거_칸(증거들, 만들기):
    return "<br>".join(칸에_넣기(만들기(증거)) for 증거 in 증거들) or "없음"


def 두_판단_만들기(결과, 진단):
    """원인 추론과 업무 결정을 근거와 함께 나누어 적는다."""
    줄들 = ["## 두 판단", "", "원인이 무엇인지와 어떤 조치를 권하는지는 서로 다른 근거로 내린 판단이다.", ""]

    줄들.extend([
        "### 원인 추론", "",
        f"근거: {원인_진단_이름}의 증거(확인한 것을 잰 값과 그 기준).", "",
        "| 원인 후보 | 확인한 것 | 잰 값 | 기준 | 판정 | 점수 |",
        "|---|---|---|---|---|---|",
    ])
    for 원인 in 진단["원인_후보"]:
        if not isinstance(원인, dict):
            continue
        증거들 = [증거 for 증거 in 원인.get("증거") or [] if isinstance(증거, dict)]
        줄들.append(
            f"| {칸에_넣기(값_보이기(원인.get('원인')))} "
            f"| {증거_칸(증거들, lambda 증거: 값_보이기(증거.get('확인한_것')))} "
            f"| {증거_칸(증거들, lambda 증거: 값_보이기(증거.get('잰_값'), 증거.get('단위') or ''))} "
            f"| {증거_칸(증거들, lambda 증거: 값_보이기(증거.get('기준')))} "
            f"| {증거_칸(증거들, lambda 증거: 값_보이기(증거.get('판정')))} "
            f"| {칸에_넣기(값_보이기(원인.get('점수')))} |"
        )
    줄들.extend(["", f"가려진 원인: {값_보이기(진단.get('가려진_원인'))}", ""])

    줄들.extend([
        "### 업무 결정", "",
        "근거: 규칙을 통과해 남은 후보의 네 지표(아래 요청별 표)와 그 합계의 순위.", "",
        "| 요청 번호 | 비교 대상 수 | 추천 | 추천한 후보의 합계 (만 원) |",
        "|---|---|---|---|",
    ])
    for 비교 in 결과:
        추천, 합계 = "조치 불가", "없음"
        for 후보 in 비교["후보별_지표"]:
            if 비교["추천"] is not None and 후보["후보"] == 비교["추천"]:
                추천 = 후보["후보"]
                # 새로 계산하지 않고, 요청별 표에 적은 네 값을 그대로 더한다.
                합계 = 돈(sum((후보[이름] for 이름 in 지표_이름), Decimal(0)))
        줄들.append(
            f"| {칸에_넣기(비교['번호'])} | {len(비교['비교_대상'])} | {칸에_넣기(추천)} | {합계} |"
        )
    줄들.append("")
    return 줄들


def md_만들기(결과, 진단):
    줄들 = ["# 비교 결과", "", "지표의 값은 그 조치를 했을 때 예상되는 손실 금액이고 단위는 만 원이다. 작을수록 좋다.", ""]
    줄들.extend(두_판단_만들기(결과, 진단))
    for 비교 in 결과:
        줄들.append(f"## {비교['번호']}")
        줄들.append("")
        줄들.append(f"- 비교 대상: {', '.join(비교['비교_대상']) or '없음'}")
        줄들.append(f"- 추천: {비교['추천'] or '없음'}")
        줄들.append("")
        줄들.append("| 후보 | 비용 | 생산 | 품질 | 에너지 | 합계 | 순위 |")
        줄들.append("|---|---|---|---|---|---|---|")
        for 후보 in 비교["후보별_지표"]:
            값들 = " | ".join(
                "계산 불가" if 후보[이름] is None else 돈(후보[이름]) for 이름 in 지표_이름
            )
            # 합계는 이 줄에 적은 네 값을 더한 것이다. 값이 하나라도 없으면 더하지 않는다.
            if any(후보[이름] is None for 이름 in 지표_이름):
                합계 = "계산 불가"
            else:
                합계 = 돈(sum((후보[이름] for 이름 in 지표_이름), Decimal(0)))
            순위 = "없음" if 후보["순위"] is None else 후보["순위"]
            절차_번호 = 칸에_넣기(후보["후보"])
            if 비교["추천"] is not None and 후보["후보"] == 비교["추천"]:
                절차_번호 = f"**{절차_번호}**"
            줄들.append(f"| {절차_번호} | {값들} | {합계} | {순위} |")
        줄들.append("")
        줄들.append(f"추천 사유: {비교['추천_사유']}")
        줄들.append("")
    return "\n".join(줄들)


def main():
    try:
        업무, 표준_작업 = 업무_값_읽기()
        설정들 = 후보_설정_읽기()
        요청들 = 요청_읽기()
        판정들 = 판정_결과_읽기()
        진단 = 원인_진단_읽기()
        요청_번호들 = [요청["번호"] for 요청 in 요청들]
        for 번호 in 요청_번호들:
            if 번호 not in 판정들:
                raise 멈춤(f"요청 {번호}의 판정 결과가 {판정_결과_이름}에 없습니다.")
        for 번호 in 판정들:
            if 번호 not in 요청_번호들:
                raise 멈춤(f"{판정_결과_이름}의 {번호}가 {요청_이름}에 없습니다.")
    except 멈춤 as 까닭:
        print(f"비교를 멈춥니다: {까닭}", file=sys.stderr)
        return 1
    except (OSError, json.JSONDecodeError, csv.Error) as 까닭:
        print(f"비교를 멈춥니다: 파일을 읽지 못했습니다. {까닭}", file=sys.stderr)
        return 1

    결과 = [요청_비교(요청, 판정들[요청["번호"]], 업무, 표준_작업, 설정들) for 요청 in 요청들]
    json_글 = json_적기(결과) + "\n"
    md_글 = md_만들기(결과, 진단)

    결과_json_경로.parent.mkdir(exist_ok=True)
    with open(결과_json_경로, "w", encoding="utf-8", newline="\n") as 파일:
        파일.write(json_글)
    with open(결과_md_경로, "w", encoding="utf-8", newline="\n") as 파일:
        파일.write(md_글)
    return 0


if __name__ == "__main__":
    sys.exit(main())
