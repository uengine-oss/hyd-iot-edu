"""요청 처리 고리. 점검 요청마다 사례를 정하고, 정해지면 에이전트로 점검 계획을 받는다.
빠진 값은 짐작하지 않고 사람에게 묻고 멈추며, 사람이 승인하기 전에는 확정으로 적지 않는다.

    python 요청_처리.py
"""
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # __pycache__를 만들지 않는다

import 에이전트  # noqa: E402

_폴더 = Path(__file__).resolve().parent
_정의_경로 = _폴더 / "에이전트_정의.json"
_요청_경로 = _폴더 / "입력" / "점검_요청.json"
_입력_경로 = _폴더 / "입력" / "센서_입력.json"
_답변_경로 = _폴더 / "사람" / "답변.json"
_승인_경로 = _폴더 / "사람" / "승인.json"
_결과_폴더 = _폴더 / "결과"

_사례_칸 = ("번호", "설비", "경보_패턴", "판단_시각")  # 센서 입력에서 직접 읽는 칸
_좁히는_칸 = {"설비": "설비", "경보_패턴": "경보 패턴"}
_승인_칸 = ("결정", "절차_번호", "역할", "이름", "사유")
_선택지_한도 = 8
# 긴급으로 보는 경보 패턴의 코드. 설비가 이미 멈춘 인터록 트립 셋이다
_긴급_패턴 = ("OVERHEAT_TRIP", "LOW_PRESSURE_TRIP", "HIGH_VIBRATION_TRIP")
_긴급_표시 = "[긴급] "
_표시 = "승인 전 · 확정 아님"


def _읽기(경로):
    try:
        with open(경로, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError) as 까닭:
        raise SystemExit(f"{경로.name}을(를) 읽지 못해 결과를 쓰지 않는다: {까닭}")


def _목록_읽기(경로):
    목록 = _읽기(경로)
    if not isinstance(목록, list):
        raise SystemExit(f"{경로.name}이(가) 목록이 아니어서 결과를 쓰지 않는다")
    return 목록


def _글(값):
    return json.dumps(값, ensure_ascii=False)


def _사례_글(사례):
    return (f"{사례['번호']} (설비 {사례['설비']}, 경보 패턴 {사례['경보_패턴']},"
            f" 판단 시각 {사례['판단_시각']})")


def _값들(후보, 칸):
    """후보 사례들의 그 칸에 나오는 값. 입력에 적힌 순서대로, 같은 값은 한 번만."""
    값들 = []
    for 사례 in 후보:
        if 사례[칸] not in 값들:
            값들.append(사례[칸])
    return 값들


def _결정_살피기(결정, 계획):
    """결정 한 건의 (새 상태, 받지 않는 까닭). 받으면 까닭이 None이다."""
    종류 = 결정.get("결정")
    if 종류 == "거절":
        사유 = 결정.get("사유")
        if isinstance(사유, str) and 사유.strip():
            return "반려", None
        return None, "거절의 사유가 없음"
    if 종류 != "승인":
        return None, "결정이 승인도 거절도 아님"

    # 원인마다 낸 점검은 점검 순서의 뒤쪽에, 해당 없음을 뺀 후보 원인과 같은 순서로 있다
    절차 = 결정.get("절차_번호")
    남는_원인 = [c for c in 계획["후보_원인"] if c["구분"] != "해당_없음"]
    원인_점검 = 계획["점검_순서"][len(계획["점검_순서"]) - len(남는_원인):]
    붙은_구분 = [
        원인["구분"] for 원인, 점검 in zip(남는_원인, 원인_점검)
        if any(j["절차_번호"] == 절차 for j in 점검["점검"]["조치"])
    ]
    if not 붙은_구분:
        return None, "절차 번호가 이 요청의 점검 계획에 붙은 조치가 아님"
    if "확인됨" not in 붙은_구분:
        return None, "확인된 원인에 붙은 조치가 아님(가설인 원인에만 붙어 있음)"

    # 승인 역할과 단계는 에이전트가 도구에서 받아 둔 것에서 찾는다
    받은_조치 = next(
        조치 for 호출_한_건 in 계획["호출_기록"] if 호출_한_건["도구"] == "조치_방법"
        for 조치 in 호출_한_건["받음"]["조치"] if 조치["sopId"] == 절차
    )
    if 받은_조치["승인_역할"] is None:
        return None, "승인 역할이 등록되지 않은 조치"
    if any("금지" in (s.get("text") or "") for s in 받은_조치["steps"]):
        return None, "단계에 금지 문구가 있는 조치"
    승인_역할 = 받은_조치["승인_역할"]["name"]
    if 결정.get("역할") != 승인_역할:
        return None, f"역할이 그 조치의 승인 역할({승인_역할})과 다름"
    return "확정", None


def 요청_처리(요청, 사례들, 답들, 결정들, 허용):
    """요청 한 건의 (결과 항목, 점검 계획). 사례가 정해지지 않았으면 계획은 None이다."""
    번호 = 요청["번호"]
    내_답 = [a for a in 답들 if isinstance(a, dict) and a.get("요청") == 번호]
    내_결정 = [d for d in 결정들 if isinstance(d, dict) and d.get("요청") == 번호]
    질문 = []
    기록 = []

    def 적기(상태, 까닭):
        기록.append({"순번": len(기록) + 1, "상태": 상태, "까닭": 까닭})

    적기("접수", "요청을 받음")

    # 요청에 적힌 설비와 경보 패턴에 모두 맞는 사례
    조건 = {칸: 요청[칸] for 칸 in _좁히는_칸 if 요청[칸] is not None}
    맞는 = [s for s in 사례들 if all(s[칸] == 값 for 칸, 값 in 조건.items())]
    조건_글 = ", ".join(f"{_좁히는_칸[칸]} {값}" for 칸, 값 in 조건.items()) \
        or "적힌 설비와 경보 패턴 없음"

    사례 = None
    정한_까닭 = ""
    물어야_함 = False
    if 요청["사례"] is None:
        후보 = 맞는
        머리 = (f"요청에 사례가 적혀 있지 않습니다. 요청에 적힌 것({조건_글})에 맞는 사례는"
              f" {len(맞는)}건입니다.")
    else:
        적힌_건 = next((s for s in 사례들 if s["번호"] == 요청["사례"]), None)
        if 적힌_건 is None:
            후보, 물어야_함 = 맞는, True
            머리 = (f"센서 입력에 없는 사례 번호가 요청에 적혀 있습니다({_글(요청['사례'])})."
                  f" 요청에 적힌 것({조건_글})에 맞는 사례는 {len(맞는)}건입니다.")
        elif 적힌_건 in 맞는:
            사례 = 적힌_건
            정한_까닭 = "요청에 적힌 사례 · "
        else:
            후보, 물어야_함 = ([적힌_건] + 맞는 if 맞는 else []), True
            머리 = (f"요청에 적힌 사례는 {_사례_글(적힌_건)}인데, 요청에 적힌 것({조건_글})과"
                  f" 다릅니다. 요청에 적힌 것에 맞는 사례는 {len(맞는)}건입니다.")

    # 질문은 한 번에 하나만 내고, 답이 없거나 받을 수 없으면 거기서 멈춘다
    쓴_답 = []
    while 사례 is None:
        if len(후보) == 1 and not 물어야_함:
            사례 = 후보[0]
            정한_까닭 += ("맞는 사례가 하나 남음 · " if 질문
                      else f"요청에 적힌 것({조건_글})에 맞는 사례가 하나뿐임 · ")
            break
        순번 = len(질문) + 1
        칸 = None
        if not 후보:
            선택지, 받는_값 = [], [s["번호"] for s in 사례들]
            물음 = 머리 + " 처리할 사례의 번호를 적어 주세요. 센서 입력에 있는 사례 번호만 받습니다."
        elif len(후보) <= _선택지_한도:
            선택지 = 받는_값 = [s["번호"] for s in 후보]
            물음 = 머리 + " 어느 사례를 처리할까요? " + " / ".join(_사례_글(s) for s in 후보)
        else:
            칸 = next((k for k in _좁히는_칸 if 1 < len(_값들(후보, k)) <= _선택지_한도), None)
            if 칸 is not None:
                선택지 = 받는_값 = _값들(후보, 칸)
                물음 = (머리 + f" 선택지 한도 {_선택지_한도}개를 넘어 사례를 바로 고를 수 없습니다."
                      f" 어느 {_좁히는_칸[칸]}입니까?")
            else:
                선택지, 받는_값 = [], [s["번호"] for s in 후보]
                물음 = (머리 + f" 선택지 한도 {_선택지_한도}개를 넘고 설비와 경보 패턴으로 더 좁힐 수"
                      " 없습니다. 처리할 사례의 번호를 적어 주세요. 맞는 사례의 번호만 받습니다.")
        질문.append({"순번": 순번, "물음": 물음, "선택지": 선택지, "답": None})
        적기("질문_대기", 정한_까닭 + f"질문 {순번}번을 냄")

        답_건 = next(
            (a for a in 내_답
             if isinstance(a.get("질문"), int) and not isinstance(a.get("질문"), bool)
             and a["질문"] == 순번),
            None,
        )
        if 답_건 is None:
            break
        쓴_답.append(답_건)
        답 = 답_건.get("답")
        답_글 = f"질문 {순번}번의 답 {_글(답)}(답한 사람 {_글(답_건.get('답한_사람'))})"
        if not isinstance(답, str) or 답 not in 받는_값:
            적기("질문_대기", f"{답_글}을 반영하지 않음: "
                 + ("선택지에 없음" if 선택지 else "받을 수 있는 사례 번호가 아님"))
            break
        질문[-1]["답"] = 답
        정한_까닭 = f"{답_글}을 반영함 · "
        물어야_함 = False
        if 칸 is not None:
            후보 = [s for s in 후보 if s[칸] == 답]
            머리 = f"질문 {순번}번의 답({_좁히는_칸[칸]} {답})에 맞는 사례는 {len(후보)}건입니다."
        else:
            사례 = next(s for s in 사례들 if s["번호"] == 답)

    상태 = "질문_대기"
    계획 = None
    if 사례 is not None:
        계획 = 에이전트.사례_처리(사례, 허용)
        상태 = "승인_대기" if 계획["근거_상태"] == "SUPPORTED" else "보류"
        적기(상태, 정한_까닭 + f"사례 {사례['번호']}의 점검 계획을 받음"
             f" · 근거 상태 {계획['근거_상태']}")

    # 쓰지 않은 답도 까닭을 남긴다
    for 답_건 in 내_답:
        if any(답_건 is 쓴 for 쓴 in 쓴_답):
            continue
        낸_질문 = any(답_건.get("질문") == q["순번"] for q in 질문)
        적기(상태, f"답 {_글(답_건)}을 반영하지 않음: "
             + ("같은 질문의 답은 첫 건만 씀" if 낸_질문 else "낸 적이 없는 질문 순번"))

    승인 = None
    for i, 결정 in enumerate(내_결정):
        if i > 0:
            까닭 = "그 요청의 결정은 첫 건만 씀"
        elif 상태 != "승인_대기":
            까닭 = f"승인_대기가 아닌 요청({상태})에 온 결정"
        else:
            새_상태, 까닭 = _결정_살피기(결정, 계획)
            if 까닭 is None:
                상태 = 새_상태
                승인 = {칸: 결정.get(칸) for 칸 in _승인_칸}
                적기(상태, f"결정 {_글(결정)}을 반영함")
                continue
        적기(상태, f"결정 {_글(결정)}을 반영하지 않음: {까닭}")

    # 긴급은 정해진 사례의 경보 패턴으로, 사례가 정해지기 전에는 요청에 적힌 것으로 가린다
    패턴 = 사례["경보_패턴"] if 사례 is not None else 요청["경보_패턴"]
    return {
        "번호": 번호,
        "긴급": 패턴 in _긴급_패턴,
        "상태": 상태,
        "사례": 사례 and 사례["번호"],
        "질문": 질문,
        "근거_상태": 계획 and 계획["근거_상태"],
        "승인": 승인,
        "상태_기록": 기록,
    }, 계획


def _긴급_먼저(결과들, 계획들):
    """긴급인 요청을 앞에 둔 (결과들, 계획들). 묶음 안에서는 받은 차례 그대로다."""
    쌍 = sorted(zip(결과들, 계획들), key=lambda 한_쌍: not 한_쌍[0]["긴급"])
    return [결과 for 결과, _ in 쌍], [계획 for _, 계획 in 쌍]


def _머리표(결과):
    return _긴급_표시 if 결과["긴급"] else ""


def _할_일(결과들, 계획들):
    """맨 위에 모아 적는 「사람이 할 일」 절. 요청마다의 절에 있는 것을 세 묶음으로 추린다."""
    줄 = ["## 사람이 할 일", ""]

    줄 += ["### 답할 질문", ""]
    답할_것 = [(결과, q) for 결과 in 결과들 if 결과["상태"] == "질문_대기"
            for q in 결과["질문"] if q["답"] is None]
    if not 답할_것:
        줄.append("없음")
    for 결과, q in 답할_것:
        줄.append(f"- {_머리표(결과)}{결과['번호']} · 질문 {q['순번']}번 · 선택지: "
                 + (", ".join(q["선택지"]) if q["선택지"] else "없음"))
    줄.append("")

    줄 += ["### 승인을 기다리는 요청", ""]
    기다리는_것 = [(결과, 계획) for 결과, 계획 in zip(결과들, 계획들)
              if 결과["상태"] == "승인_대기"]
    if not 기다리는_것:
        줄.append("없음")
    for 결과, 계획 in 기다리는_것:
        줄.append(f"- {_머리표(결과)}{결과['번호']} · 사례 {결과['사례']}")
        적은_것 = []
        for 점검 in 계획["점검_순서"]:
            for j in 점검["점검"]["조치"]:
                if (j["절차_번호"], j["시점"]) in 적은_것:
                    continue
                적은_것.append((j["절차_번호"], j["시점"]))
                줄.append(f"  - [{_표시}] {j['절차_번호']} {j['이름']}"
                         f" · 승인 역할 {j['승인_역할']} · {j['시점']}")
    줄.append("")

    # 반영하지 않은 것은 상태 기록의 까닭에 그렇게 적혀 있다
    줄 += ["### 반영하지 않은 사람의 기록", ""]
    남은_것 = [(결과, 한_건) for 결과 in 결과들 for 한_건 in 결과["상태_기록"]
            if "반영하지 않음" in 한_건["까닭"]]
    if not 남은_것:
        줄.append("없음")
    for 결과, 한_건 in 남은_것:
        줄.append(f"- {_머리표(결과)}{결과['번호']} · {한_건['까닭']}")
    줄.append("")
    return 줄


def 마크다운(결과들, 계획들):
    줄 = ["# 요청 처리", ""]
    결과들, 계획들 = _긴급_먼저(결과들, 계획들)
    줄 += _할_일(결과들, 계획들)
    for 결과, 계획 in zip(결과들, 계획들):
        확정 = 결과["상태"] == "확정"
        줄 += [f"## {_머리표(결과)}{결과['번호']}", "",
              f"- 상태: **{결과['상태']}**",
              f"- 사례: {결과['사례'] or '정해지지 않음'}",
              f"- 근거 상태: {결과['근거_상태'] or '사례가 정해지지 않음'}", ""]

        줄 += ["### 질문", ""]
        if not 결과["질문"]:
            줄.append("없음")
        for q in 결과["질문"]:
            줄.append(f"{q['순번']}. {q['물음']}")
            줄.append("   - 선택지: " + (", ".join(q["선택지"]) if q["선택지"] else "없음"))
            줄.append("   - 답: " + ("아직 반영한 답 없음" if q["답"] is None else q["답"]))
        줄.append("")

        줄 += ["### 승인", ""]
        승인 = 결과["승인"]
        if 승인 is None:
            줄.append("반영한 결정 없음")
        else:
            줄.append(f"{승인['결정']} · 절차 번호 {_글(승인['절차_번호'])} · {승인['역할']}"
                     f" {승인['이름']} · 사유 {_글(승인['사유'])}")
        줄.append("")

        줄 += ["### 점검 순서와 조치" + ("" if 확정 else f" ({_표시})"), ""]
        if 계획 is None:
            줄.append("사례가 정해지지 않아 점검 계획이 없음")
        elif not 계획["점검_순서"]:
            줄.append("에이전트가 낸 점검 순서 없음")
        else:
            for 점검 in 계획["점검_순서"]:
                머리 = "" if 확정 else f"[{_표시}] "
                줄.append(f"{점검['순번']}. {머리}{점검['점검']['내용']}")
                for j in 점검["점검"]["조치"]:
                    if not 확정:
                        표시 = _표시
                    elif j["절차_번호"] == 승인["절차_번호"]:
                        표시 = f"승인됨 · {승인['역할']} {승인['이름']}"
                    else:
                        표시 = "승인되지 않음"
                    줄.append(f"   - [{표시}] {j['절차_번호']} {j['이름']}"
                             f" · 승인 역할 {j['승인_역할']}")
        줄.append("")

        줄 += ["### 상태 기록", ""]
        for 한_건 in 결과["상태_기록"]:
            줄.append(f"{한_건['순번']}. {한_건['상태']} — {한_건['까닭']}")
        줄.append("")
    return "\n".join(줄)


