def 장들(path, 열쇠):
    """덱 MD를 장 블록으로 나누어 {열쇠: (제목, 본문)}으로 돌려준다. 열쇠가 겹치면 멈춘다."""
    글 = path.read_text(encoding="utf-8")
    결과 = {}
    for 블록 in re.split(r"(?m)^(?=## SLIDE )", 글)[1:]:
        첫줄, _, 본문 = 블록.partition("\n")
        m = re.match(r"## SLIDE (\[?\w+\]?) — (.+?)\s*$", 첫줄)
        assert m, f"{path.name}: 장 머리를 읽지 못함: {첫줄!r}"
        번호, 장제목 = m.group(1), m.group(2)
        k = 열쇠(번호, 장제목)
        assert k not in 결과, f"{path.name}: 장이 겹침: {k}"
        결과[k] = (장제목, 본문.strip("\n"))
    return 결과


