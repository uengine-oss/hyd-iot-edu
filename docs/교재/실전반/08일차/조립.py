HEAD = (
    "<!-- 이 파일은 조립.py가 만든다. 직접 고치지 않는다. "
    "가져오는 장의 순서와 손질은 조립.py에서 고친다. -->\n"
    "# 실전반 8일차 — 온톨로지 · 에이전트 · 프로세스의 연결과 적용\n\n"
    "통합반 11일차에서 장을 가져와 조립했다. 그림은 통합반 폴더의 것을 그대로 쓴다. "
    "기술 사실의 근거는 `docs/교재/기준/통합반_09-11일차_기술사실표.md`다.\n\n"
)


def main():
    src = blocks(SRC)
    out, count = [HEAD], {"가져옴": 0, "손질": 0}
    for no, (key, edits) in enumerate(ORDER, 1):
        assert key in src, f"통합반 {DAY}일차에서 장을 찾지 못함: {key}"
        block = apply(src[key], edits, f"{no}번 「{key}」")
        block = block.replace("- 그림: 그림/", f"- 그림: ../../통합반/{DAY}일차/그림/")
        for pic in re.findall(r"(?m)^- 그림: (\S+)", block):
            assert pic.startswith("../../통합반/") and (HERE / pic).is_file(), f"{no}번 「{key}」: 그림이 없음: {pic}"
        count["손질" if edits else "가져옴"] += 1
        body = block.split("\n", 1)[1]
        out.append(f"## SLIDE {no:02d} — {key}\n{body}\n")
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT.parent.parent)} 만듦: 전체 {len(ORDER)}장 "
          f"(가져옴 {count['가져옴']}, 가져옴·손질 {count['손질']}, 새로 0)")


if __name__ == "__main__":
    main()
