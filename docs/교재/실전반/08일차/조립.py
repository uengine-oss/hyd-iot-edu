def blocks(path):
    """덱 MD를 {제목: 장 블록}으로 나눈다. 같은 제목이 둘이면 멈춘다."""
    text = path.read_text(encoding="utf-8")
    out = {}
    for part in re.split(r"(?m)^(?=## SLIDE )", text)[1:]:
        m = re.match(r"## SLIDE (\S+) — (.*)\n", part)
        assert m, f"{path.name}: 장 머리를 읽지 못함: {part[:40]!r}"
        key = m.group(2).strip()
        assert key not in out, f"{path.name}: 제목이 겹침: {key}"
        out[key] = part.rstrip() + "\n"
    return out


def G(title, *edits):
    """가져오는 장. edits는 (찾을 말, 바꿀 말)이며 찾을 말은 장 안에 정확히 한 번 있어야 한다."""
    return (title, edits)


def apply(block, edits, where):
    """바꾸기를 한 번에 적용한다. 원문에서만 찾으므로 방금 바꾼 말이 다시 걸리지 않는다."""
    if not edits:
        return block
    table = dict(edits)
    assert len(table) == len(edits), f"{where}: 찾을 말이 겹침"
    for old in table:
        assert block.count(old) == 1, f"{where}: 바꿀 말이 {block.count(old)}번 있음: {old}"
    olds = sorted(table, key=len, reverse=True)
    for a in olds:
        assert not any(a != b and a in b for b in olds), f"{where}: 찾을 말이 다른 찾을 말 안에 있음: {a}"
    return re.sub("|".join(re.escape(o) for o in olds), lambda m: table[m.group(0)], block)


