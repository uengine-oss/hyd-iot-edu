def sheet_table(wb, name, cls, kind):
    ws = wb.create_sheet(name)
    hdr, widths = (VIDEO_HDR, VIDEO_W) if kind == "v" else (OFF_HDR, OFF_W)
    ncol = len(hdr)
    last_col = chr(ord("A") + ncol - 1)
    center_cols = {1, 2, 7, 8, 9} if kind == "v" else {1, 2, 7}
    for c, w in widths.items():
        ws.column_dimensions[c].width = w
    for j, h in enumerate(hdr, 1):
        style(ws.cell(1, j, h), bold=True, color=WHITE, bg=NAVY, center=True)
    mins = part_minutes(cls, kind)
    nums = video_numbers() if kind == "v" else offline_numbers()
    r, cur, title_rows = 1, None, []
    for row in ROWS:
        if kind == "o" and row["do"] is None:
            continue
        if row["p"] != cur:
            cur = row["p"]
            part = next(p for p in PARTS if p["no"] == cur)
            r += 1
            style(ws.cell(r, 1), bold=True, color=NAVY, bg=BLUE)
            style(ws.cell(r, 2, f"{cur}. {part['title']}  ({mins[cur]}분)"), bold=True, color=NAVY, bg=BLUE)
            ws.merge_cells(f"B{r}:{last_col}{r}")
            title_rows.append(r)
