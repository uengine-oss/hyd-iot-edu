# ── 행 높이: 글자 폭(한글·전각 2, 그 밖 1)으로 단어 단위 줄바꿈을 흉내 내 줄 수를 센다 ──
def char_w(ch):
    if ch == " ":
        return 0.7
    ea = unicodedata.east_asian_width(ch)
    return 2.0 if ea in ("W", "F", "A") else 1.05


def text_lines(text, col_width):
    if text is None or text == "":
        return 1
    avail = max(4.0, col_width - 2.0)  # 셀 안쪽 여백
    total = 0
    for para in str(text).split("\n"):
        line, lines = 0.0, 1
        for word in para.split(" "):
            w = sum(char_w(c) for c in word)
            add = w if line == 0 else w + char_w(" ")
            if line + add <= avail:
                line += add
            elif w <= avail:
                lines += 1
                line = w
            else:  # 한 단어가 칸보다 길면 글자 단위로 끊긴다
                rest = line + add
                while rest > avail:
                    lines += 1
                    rest -= avail
                line = rest
        total += lines
    return total


def row_height(lines):
    return round(lines * 15 + 7, 1)


def fit_rows(ws, widths, first_row=1, skip_rows=()):
    for r in range(first_row, ws.max_row + 1):
        if r in skip_rows:
            continue
        lines = 1
        for col, w in widths.items():
            v = ws[f"{col}{r}"].value
            if isinstance(v, str) and v.startswith("="):
                continue
            lines = max(lines, text_lines(v, w))
        ws.row_dimensions[r].height = row_height(lines)


