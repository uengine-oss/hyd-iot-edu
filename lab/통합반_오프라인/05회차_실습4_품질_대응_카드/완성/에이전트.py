"""불량 접수를 분류 기준에 대어 품질 대응 카드로 바꾸는 실행 고리.

    python 에이전트.py        모든 접수를 처리한다
    python 에이전트.py Q01    그 접수만 처리한다

분류 기준은 도구로만 읽는다. 도구는 `에이전트_정의.json`의 `도구` 목록에 있는 것만 부른다.
"""

import json
import re
import sys
from pathlib import Path

import 도구

폴더 = Path(__file__).resolve().parent
정의_파일 = 폴더 / "에이전트_정의.json"
접수_파일 = 폴더 / "접수" / "불량_접수.json"
결과_json = 폴더 / "결과" / "품질_대응_카드.json"
결과_md = 폴더 / "결과" / "품질_대응_카드.md"

미분류 = "미분류"
미분류_항목 = "품질 유형"
단서_없음 = "걸린 단서 없음"
찾지_못함 = "본문에서 찾지 못함"
확인_부탁 = "확인 부탁드립니다: "
유형의_조치_부서 = "유형의_조치_부서"


def 읽기(파일):
    with open(파일, encoding="utf-8") as 열린_파일:
        return json.load(열린_파일)


def 부르기(이름, 물음, 허용_목록, 기록):
    """허용 목록에 있는 도구만 부르고, 부른 것을 기록에 남긴다."""
    if 이름 not in 허용_목록:
        raise RuntimeError(f"허용 목록에 없는 도구입니다: {이름}")
    함수 = getattr(도구, 이름, None)
    if 함수 is None:
        raise RuntimeError(f"도구.py에 없는 도구입니다: {이름}")
    받음 = 함수() if 물음 == "" else 함수(물음)
    기록.append({"도구": 이름, "물음": 물음, "받음": 받음})
    return 받음


def 걸린_단서(본문, 단서_목록):
    걸림 = []
    for 단서 in 단서_목록:
        if 단서 in 본문 and 단서 not in 걸림:
            걸림.append(단서)
    return 걸림


def 본문에_있음(본문, 정보):
    if "정규식" in 정보:
        return re.search(정보["정규식"], 본문) is not None
    if "낱말" in 정보:
        return any(낱말 in 본문 for 낱말 in 정보["낱말"])
    raise RuntimeError(f"찾는 법이 적히지 않은 확인 정보입니다: {정보['이름']}")


def 원인_문장(본문, 표현_목록):
    """원인을 말하는 표현이 든 문장 가운데 먼저 나온 것. 없으면 빈 글."""
    for 문장 in re.split(r"(?<=[.?!])\s+", 본문.strip()):
        if any(표현 in 문장 for 표현 in 표현_목록):
            return 문장
    return ""


def 틀_채우기(틀, 값):
    def 넣기(자리):
        이름 = 자리.group(1)
        if 이름 not in 값:
            raise RuntimeError(f"틀의 자리에 넣을 값이 없습니다: {이름}")
        return 값[이름]

    return re.sub(r"\{([^{}]+)\}", 넣기, 틀)


def 카드_만들기(접수, 허용_목록):
    번호, 보낸_곳, 본문 = 접수["번호"], 접수["보낸_곳"], 접수["본문"]
    기록 = []

    # 유형: 걸린 단서의 가짓수가 가장 많은 유형. 둘 이상이거나 하나도 없으면 미분류.
    기준 = 부르기("분류_기준", "", 허용_목록, 기록)
    후보 = [(유형, 걸린_단서(본문, 유형["단서"])) for 유형 in 기준["유형"]]
    가장_많음 = max((len(걸림) for _, 걸림 in 후보), default=0)
    으뜸 = [(유형, 걸림) for 유형, 걸림 in 후보 if 걸림 and len(걸림) == 가장_많음]

    값 = {"보낸_곳": 보낸_곳, "번호": 번호}
    유형_기준 = None
    if len(으뜸) == 1:
        유형, 걸림 = 으뜸[0]
        품질_유형 = {"코드": 유형["코드"], "이름": 유형["이름"], "단서": 걸림}
        유형_기준 = 부르기("유형_기준", 유형["코드"], 허용_목록, 기록)
        if 유형_기준 is None:
            raise RuntimeError(f"분류 기준에 없는 유형입니다: {유형['코드']}")
        추가_확인_항목 = [
            {"항목": 정보["이름"], "까닭": 찾지_못함}
            for 정보 in 유형_기준["확인_정보"]
            if not 본문에_있음(본문, 정보)
        ]
        값["유형_이름"] = 유형["이름"]
        값["기본_조치"] = 유형_기준["기본_조치"]
    else:
        품질_유형 = {
            "코드": 미분류,
            "이름": 미분류,
            "단서": [단서 for _, 걸림 in 으뜸 for 단서 in 걸림],
        }
        까닭 = ", ".join(유형["이름"] for 유형, _ in 으뜸) or 단서_없음
        추가_확인_항목 = [{"항목": 미분류_항목, "까닭": 까닭}]

    # 원인: 대장에 걸린 분석이 종결일 때만 확정. 진행이면 대장의 원인을, 대장에 없으면 본문의 문장을 근거로 적는다.
    # 미분류 카드는 대장을 보지 않는다.
    분석 = {"있음": False}
    if 품질_유형["코드"] != 미분류:
        분석 = 부르기("원인_분석", 번호, 허용_목록, 기록)
    원인_상태 = "미확정"
    if 분석["있음"]:
        if 분석["상태"] == "종결":
            원인_상태 = "확정"
            원인_근거 = {"내용": 분석["원인"], "출처": "분석_종결"}
            값["원인"] = 분석["원인"]
        elif 분석["상태"] == "진행":
            원인_근거 = {"내용": 분석["원인"], "출처": "분석_진행"}
        else:
            raise RuntimeError(f"대장의 상태를 알 수 없습니다: {분석['분석_번호']} {분석['상태']}")
    else:
        문장 = 원인_문장(본문, 기준["원인을_말하는_표현"])
        원인_근거 = {"내용": 문장, "출처": "접수자_의견" if 문장 else "없음"}

    if 품질_유형["코드"] == 미분류:
        갈래 = "재분류"
    elif 원인_상태 == "확정":
        갈래 = "시정_조치"
    else:
        갈래 = "조사_요청"

    갈래_기준 = 부르기("대응_틀", 갈래, 허용_목록, 기록)
    if 갈래_기준 is None:
        raise RuntimeError(f"분류 기준에 없는 갈래입니다: {갈래}")
    담당_부서 = 갈래_기준["담당"]
    if 담당_부서 == 유형의_조치_부서:
        담당_부서 = 유형_기준["조치_부서"]
    값["담당_부서"] = 담당_부서

    대응_초안 = 틀_채우기(갈래_기준["틀"], 값)
    if 추가_확인_항목 and 품질_유형["코드"] != 미분류:
        대응_초안 += " " + 확인_부탁 + ", ".join(항목["항목"] for 항목 in 추가_확인_항목)

    return {
        "번호": 번호,
        "품질_유형": 품질_유형,
        "추가_확인_항목": 추가_확인_항목,
        "원인_상태": 원인_상태,
        "원인_근거": 원인_근거,
        "갈래": 갈래,
        "담당_부서": 담당_부서,
        "대응_초안": 대응_초안,
        "호출_기록": 기록,
    }


def 찾은_확인_정보(카드, 본문):
    """찾았다고 친 확인 정보마다 이름, 본문에서 걸린 글자, 그 글자가 든 문장을 적은 줄들. 사람이 읽고 가리라고 적는다."""
    확인_정보 = None
    for 호출 in 카드["호출_기록"]:
        if 호출["도구"] == "유형_기준":
            확인_정보 = 호출["받음"]["확인_정보"]
    if 확인_정보 is None:
        return ["- 찾은 확인 정보: 유형을 정하지 못해 찾지 않음"]

    # 문장마다 본문에서의 자리(시작, 끝)를 잡아 둔다.
    자리 = []
    시작 = 0
    for 틈 in re.finditer(r"(?<=[.?!])\s+", 본문):
        자리.append((시작, 틈.start()))
        시작 = 틈.end()
    자리.append((시작, len(본문)))

    줄 = []
    for 정보 in 확인_정보:
        if "정규식" in 정보:
            모양 = 정보["정규식"]
        else:
            모양 = "|".join(re.escape(낱말) for 낱말 in 정보["낱말"])
        문장별 = {}
        for 걸림 in re.finditer(모양, 본문):
            for 문장_시작, 문장_끝 in 자리:
                if 문장_시작 <= 걸림.start() < 문장_끝 or 문장_끝 == len(본문):
                    글자들 = 문장별.setdefault((문장_시작, 문장_끝), [])
                    if 걸림.group(0) not in 글자들:
                        글자들.append(걸림.group(0))
                    break
        for (문장_시작, 문장_끝), 글자들 in 문장별.items():
            걸린_글자 = ", ".join(f"「{글자}」" for 글자 in 글자들)
            줄.append(f"  - {정보['이름']}: {걸린_글자} / 문장: {본문[문장_시작:문장_끝].strip()}")
    if not 줄:
        return ["- 찾은 확인 정보: 없음"]
    return ["- 찾은 확인 정보 (글자 모양으로만 찾은 것이니 문장을 읽고 정말 있는지 가릴 것):"] + 줄


def 사람이_읽는_글(카드_목록, 접수_목록):
    본문_찾기 = {접수["번호"]: 접수["본문"] for 접수 in 접수_목록}
    줄 = ["# 품질 대응 카드", ""]
    for 카드 in 카드_목록:
        유형 = 카드["품질_유형"]
        줄.append(f"## {카드['번호']}")
        줄.append("")
        줄.append(f"- 품질 유형: {유형['코드']} / {유형['이름']} / 단서: {', '.join(유형['단서']) or '없음'}")
        if 카드["추가_확인_항목"]:
            줄.append("- 추가 확인 항목:")
            for 항목 in 카드["추가_확인_항목"]:
                줄.append(f"  - {항목['항목']}: {항목['까닭']}")
        else:
            줄.append("- 추가 확인 항목: 없음")
        줄.extend(찾은_확인_정보(카드, 본문_찾기[카드["번호"]]))
        줄.append(f"- 원인 상태: {카드['원인_상태']}")
        출처 = f"출처: {카드['원인_근거']['출처']}"
        for 호출 in 카드["호출_기록"]:
            if 호출["도구"] == "원인_분석" and 호출["받음"]["있음"]:
                출처 += f", 분석 번호: {호출['받음']['분석_번호']}"
        줄.append(f"- 원인 근거: {카드['원인_근거']['내용'] or '없음'} ({출처})")
        줄.append(f"- 갈래: {카드['갈래']}")
        줄.append(f"- 담당 부서: {카드['담당_부서']}")
        줄.append(f"- 대응 초안: {카드['대응_초안']}")
        줄.append("- 호출 기록:")
        for 순서, 호출 in enumerate(카드["호출_기록"], 1):
            받음 = json.dumps(호출["받음"], ensure_ascii=False)
            줄.append(f"  {순서}. `{호출['도구']}({호출['물음']})` → `{받음}`")
        줄.append("")
    return "\n".join(줄)


def main(인자):
    if len(인자) > 1:
        print("쓰는 법: python 에이전트.py [접수 번호]", file=sys.stderr)
        return 2

    허용_목록 = 읽기(정의_파일)["도구"]
    접수_목록 = 읽기(접수_파일)
    if 인자:
        접수_목록 = [접수 for 접수 in 접수_목록 if 접수["번호"] == 인자[0]]
        if not 접수_목록:
            print(f"그런 접수 번호가 없습니다: {인자[0]}", file=sys.stderr)
            return 1

    카드_목록 = [카드_만들기(접수, 허용_목록) for 접수 in 접수_목록]

    결과_json.parent.mkdir(exist_ok=True)
    with open(결과_json, "w", encoding="utf-8") as 파일:
        json.dump(카드_목록, 파일, ensure_ascii=False, indent=2)
        파일.write("\n")
    with open(결과_md, "w", encoding="utf-8") as 파일:
        파일.write(사람이_읽는_글(카드_목록, 접수_목록))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
