"""에이전트가 부르는 도구.

도구는 파일을 읽어 물음에 맞는 것을 돌려주기만 하고, 판단하지 않는다.
부를 때마다 파일을 새로 읽는다.
"""

import json
from pathlib import Path

_폴더 = Path(__file__).resolve().parent
_분류_기준_파일 = _폴더 / "기준" / "분류_기준.json"
_원인_분석_대장_파일 = _폴더 / "자료" / "원인_분석_대장.json"


def _분류_기준_읽기():
    with open(_분류_기준_파일, encoding="utf-8") as 파일:
        return json.load(파일)


def 분류_기준():
    """유형의 목록(코드, 이름, 단서)과 원인을 말하는 표현을 돌려준다."""
    기준 = _분류_기준_읽기()
    return {
        "유형": [
            {"코드": 유형["코드"], "이름": 유형["이름"], "단서": 유형["단서"]}
            for 유형 in 기준["유형"]
        ],
        "원인을_말하는_표현": 기준["원인을_말하는_표현"],
    }


def 유형_기준(코드):
    """그 유형의 확인 정보(이름과 찾는 법), 조치 부서, 기본 조치를 돌려준다. 없는 코드면 None."""
    기준 = _분류_기준_읽기()
    for 유형 in 기준["유형"]:
        if 유형["코드"] == 코드:
            return {
                "코드": 유형["코드"],
                "확인_정보": [기준["확인_정보"][키] for 키 in 유형["확인_정보"]],
                "조치_부서": 유형["조치_부서"],
                "기본_조치": 유형["기본_조치"],
            }
    return None


def 대응_틀(갈래):
    """그 갈래의 담당과 대응 틀을 돌려준다. 없는 갈래면 None."""
    기준 = _분류_기준_읽기()
    갈래_기준 = 기준["갈래"].get(갈래)
    if 갈래_기준 is None:
        return None
    return {"담당": 갈래_기준["담당"], "틀": 갈래_기준["틀"]}


def 원인_분석(접수_번호):
    """원인 분석 대장에서 그 접수가 걸린 분석 건(분석 번호, 상태, 원인, 근거)을 돌려준다. 없으면 없다고 돌려준다."""
    with open(_원인_분석_대장_파일, encoding="utf-8") as 파일:
        대장 = json.load(파일)
    for 분석 in 대장:
        if 접수_번호 in 분석["접수"]:
            return {
                "있음": True,
                "분석_번호": 분석["분석_번호"],
                "상태": 분석["상태"],
                "원인": 분석["원인"],
                "근거": 분석["근거"],
            }
    return {"있음": False}
