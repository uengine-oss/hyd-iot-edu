def _읽기(경로):
    with open(경로, encoding="utf-8") as f:
        return json.load(f)


class 호출:
    """허용 목록에 있는 도구만 부르고, 부른 순서대로 적어 둔다."""

    def __init__(self, 허용):
        self.허용 = 허용
        self.기록 = []

    def 있음(self, 이름):
        return 이름 in self.허용

    def 부르기(self, 이름, **물음):
        if 이름 not in self.허용:
            raise SystemExit(f"허용 목록에 없는 도구는 부르지 않는다: {이름}")
        함수 = getattr(도구, 이름, None)
        if 함수 is None:
            raise SystemExit(f"허용 목록에는 있으나 도구.py에 없는 도구: {이름}")
        받음 = 함수(**물음)
        self.기록.append({"도구": 이름, "물음": 물음, "받음": 받음})
        return 받음


def _증거_판정(호출기, 번호, 기준, 신선함):
    """증거 한 건의 (판정, 읽은_값). 비교는 expect와 threshold 그대로 한다."""
    if not 신선함:
        return "확인하지_못함", None
    받음 = 호출기.부르기(
        "센서_집계", 사례=번호, tag=기준["tag"],
        aggregate=기준["aggregate"], windowSeconds=기준["windowSeconds"],
    ) or {}
    값 = 받음.get("value")
    관측 = 받음.get("coverage") or {}
    if 값 is None or 관측.get("covered") is not True:
        return "확인하지_못함", None
    return ("맞음" if _비교[기준["expect"]](값, 기준["threshold"]) else "아님"), 값


def _구분(판정들):
    if 판정들 and all(p == "맞음" for p in 판정들):
        return "확인됨"
    if 판정들 and all(p == "아님" for p in 판정들):
        return "해당_없음"
    return "가설"


def _근거_상태(구분들):
    if any(g == "확인됨" for g in 구분들):
        return "SUPPORTED"
    if 구분들 and all(g == "해당_없음" for g in 구분들):
        return "UNSUPPORTED"
    return "UNKNOWN"


def _붙일_조치(원인_id, 구분, 고장_유형들, 받은_조치):
    """원인 항목에 붙일 조치. 확인됨은 즉시 완화와 근본 조치, 가설은 근본 조치만."""
    붙임 = {}
    for 고장 in 고장_유형들:
        for 조치 in 받은_조치.get(고장, []):
            if 조치["맞는_원인"] and 원인_id not in 조치["맞는_원인"]:
                continue
            if 구분 == "가설" and 조치["관계"] != "REMEDIED_BY":
                continue
            첫_단계 = 조치["steps"][0] if 조치["steps"] else None
            붙임.setdefault(조치["id"], {
                "시점": "확인된 원인의 조치" if 구분 == "확인됨" else "확인된 뒤에 할 조치",
                "절차_번호": 조치["sopId"],
                "이름": 조치["name"],
                "종류": _조치_종류[조치["관계"]],
                "첫_단계": 첫_단계 and {"글": 첫_단계.get("text"), "근거_절": 첫_단계.get("section")},
                "승인_역할": 조치["승인_역할"]["name"] if 조치["승인_역할"] else "등록되지 않음",
            })
    # 즉시 완화를 앞에, 근본 조치를 뒤에 둔다(같은 종류 안에서는 온톨로지에 적힌 순서)
    return sorted(붙임.values(), key=lambda j: j["종류"] != "즉시_완화")


def _원인_글(원인):
    return f"{원인['이름']} ({원인['원인']})"


def _값_글(기준):
    return f"{기준['aggregate']}({기준['tag']}) {기준['windowSeconds']}초"


def _증거_글(e):
    기준 = e["기준"]
    return (f"{e['증거']}(읽은 값 {json.dumps(e['읽은_값'])}, 기준 {_값_글(기준)}"
            f" {기준['expect']} {json.dumps(기준['threshold'])})")


def _근거(e):
    return {"증거": e["증거"], "읽은_값": e["읽은_값"], "근거_절": e["기준"]["section"]}


def _사실_글(원인, 사전_확률):
    판정들 = [e["판정"] for e in 원인["증거"]]
    return (f"구분 {원인['구분']}, 맞음 {판정들.count('맞음')}건 · 아님 {판정들.count('아님')}건"
            f" · 확인하지_못함 {판정들.count('확인하지_못함')}건, 사전 확률 {json.dumps(사전_확률)}")


def _바꾼_구분(원인, 바꿈):
    """증거의 판정을 바꿈대로 바꿔 놓았을 때의 구분. 정하는 법은 _구분 그대로다."""
    판정들 = [바꿈(e) for e in 원인["증거"]]
    구분 = _구분(판정들)
    if 구분 != "가설":
        return 구분
    if "확인하지_못함" in 판정들:
        return "가설(확인하지 못한 증거가 남음)"
    return "가설(증거가 갈림)"


def _차례대로(것들):
    return list(dict.fromkeys(것들))


def _부족_확인(경보_패턴, 후보, 후보_원인, 못_읽은_까닭, 신선도):
    """부족인 추가 확인. 읽을 값마다 한 건, 신선도 초과 · 읽는 도구 없음 · 등록된 증거 없음은 사례에 한 건."""
    사례에_한_건 = ("읽는 도구 없음", "신선도 초과")
    묶음 = {}  # 열쇠 → [(원인, 증거)]
    for 원인 in 후보_원인:
        if not 원인["증거"]:
            묶음.setdefault(("등록된 증거 없음",), []).append((원인, None))
        for e in 원인["증거"]:
            if e["판정"] != "확인하지_못함":
                continue
            까닭 = 못_읽은_까닭[(원인["원인"], e["증거"])]
            기준 = e["기준"]
            열쇠 = (까닭,) if 까닭 in 사례에_한_건 else (
                까닭, 기준["tag"], 기준["aggregate"], 기준["windowSeconds"])
            묶음.setdefault(열쇠, []).append((원인, e))

    확인 = []
    for 열쇠, 짝들 in 묶음.items():
        이름 = 열쇠[0]
        원인들 = [c for c in 후보_원인 if any(c is 원인 for 원인, _ in 짝들)]
        원인_글 = ", ".join(_원인_글(c) for c in 원인들)
        증거들 = _차례대로(e["증거"] for _, e in 짝들 if e)
        값들 = ", ".join(_차례대로(_값_글(e["기준"]) for _, e in 짝들 if e))
        if 이름 == "등록된 증거 없음":
            대상 = [c["원인"] for c in 원인들]
            표제 = f"등록된 증거 없음 · 원인 {len(원인들)}건"
            까닭 = f"등록된 증거 없음: 원인 {len(원인들)}건에 온톨로지에 등록된 증거가 없어 센서 값으로 가릴 수 없음"
            요청 = f"다음 원인을 센서 값 밖에서 확인: {원인_글}. 확인되기 전에는 이 원인들의 구분이 가설로 남는다."
        elif 이름 in 사례에_한_건:
            대상 = 증거들
            표제 = f"{이름} · 증거 {len(증거들)}건"
            if 이름 == "신선도 초과":
                까닭 = (f"신선도 초과: 최신 {신선도.get('tag')} 값의 나이 {json.dumps(신선도.get('age_s'))}초가"
                      f" 한도 {json.dumps(신선도.get('max_age_s'))}초를 넘어 증거 {len(증거들)}건을 확인하지 못함")
                요청 = f"신선도가 한도 안으로 돌아온 뒤 다음 값을 다시 확인: {값들}."
            else:
                까닭 = f"읽는 도구 없음: 센서_집계가 허용 목록에 없어 증거 {len(증거들)}건을 확인하지 못함"
                요청 = f"다음 값을 확인: {값들}."
            요청 += f" 값이 읽혀야 {원인_글}의 구분이 정해진다."
        else:
            대상 = 증거들
            표제 = f"{이름} · {값들}"
            if 이름 == "관측 공백 초과":
                까닭 = f"관측 공백 초과: {값들} 구간의 관측 공백이 한도를 넘어 받은 값을 비교하지 않음"
            elif not 신선도:
                까닭 = f"값 없음: 신선도를 받지 못해 {값들} 구간의 값을 읽지 않음"
            else:
                까닭 = f"값 없음: {값들} 구간의 값을 받지 못함"
            갈림 = "; ".join(
                f"{e['증거']}({e['기준']['expect']} {json.dumps(e['기준']['threshold'])})의 판정이"
                f" 맞음이면 {_원인_글(원인)}의 구분은"
                f" {_바꾼_구분(원인, lambda x, e=e: '맞음' if x is e else x['판정'])},"
                f" 아님이면 {_바꾼_구분(원인, lambda x, e=e: '아님' if x is e else x['판정'])}"
                for 원인, e in 짝들)
            요청 = f"{값들} 구간 값을 다시 확인. {갈림}."
        확인.append({
            "항목": {"상황": "부족", "대상": 대상, "까닭": 까닭, "요청": 요청},
            "표제": 표제,
            "근거": [_근거(e) for _, e in 짝들 if e],
            "원인들": 원인들,
            "사례에_한_건": 이름 in 사례에_한_건,
            "증거_없음": 이름 == "등록된 증거 없음",
        })

    if not 후보_원인:
        고장_수 = len(후보["고장_유형"])
        확인.append({
            "항목": {
                "상황": "부족", "대상": [],
                "까닭": f"등록된 원인 없음: 경보 패턴 {경보_패턴}에서 이어지는 고장 유형 {고장_수}건에 등록된 원인이 없음",
                "요청": f"경보 패턴 {경보_패턴}의 원인을 온톨로지 밖에서 확인. 후보 원인이 없어 구분을 정할 수 없다.",
            },
            "표제": "등록된 원인 없음", "근거": [], "원인들": [],
            "사례에_한_건": False, "증거_없음": False,
        })
    return 확인


def _충돌_확인(경보_패턴, 후보_원인):
    """충돌인 추가 확인. (증거가 갈린 원인마다 한 건, 모두 해당_없음이면 사례에 한 건)"""
    갈린_원인 = []
    for 원인 in 후보_원인:
        맞음 = [e for e in 원인["증거"] if e["판정"] == "맞음"]
        아님 = [e for e in 원인["증거"] if e["판정"] == "아님"]
        if not (맞음 and 아님):
            continue
        까닭 = f"{_원인_글(원인)}의 증거가 맞음 {len(맞음)}건, 아님 {len(아님)}건으로 갈림."
        # 아님인 증거와 같은 값을 쓰는 증거가 다른 확인된 원인에서 맞음이면 덧붙인다
        for e in 아님:
            for 다른 in 후보_원인:
                if 다른 is 원인 or 다른["구분"] != "확인됨":
                    continue
                for d in 다른["증거"]:
                    if d["판정"] == "맞음" and _값_글(d["기준"]) == _값_글(e["기준"]):
                        까닭 += (f" 아님인 증거({e['증거']})와 같은 값({_값_글(e['기준'])})을 쓰는"
                               f" 증거({d['증거']})가 확인된 원인 {_원인_글(다른)}에서는 맞음.")
        요청 = (
            f"갈린 증거를 다시 확인: 맞음 {', '.join(_증거_글(e) for e in 맞음)};"
            f" 아님 {', '.join(_증거_글(e) for e in 아님)}."
            f" 아님인 증거가 모두 맞음으로 바뀌면 {_원인_글(원인)}의 구분은"
            f" {_바꾼_구분(원인, lambda x: '맞음' if x['판정'] == '아님' else x['판정'])},"
            f" 맞음인 증거가 모두 아님으로 바뀌면"
            f" {_바꾼_구분(원인, lambda x: '아님' if x['판정'] == '맞음' else x['판정'])}."
        )
        갈린_원인.append({
            "항목": {"상황": "충돌", "대상": [원인["원인"]], "까닭": 까닭, "요청": 요청},
            "원인들": [원인],
        })

    모두_해당_없음 = []
    if 후보_원인 and all(c["구분"] == "해당_없음" for c in 후보_원인):
        증거들 = [e for c in 후보_원인 for e in c["증거"]]
        모두_해당_없음.append({
            "항목": {
                "상황": "충돌", "대상": [c["원인"] for c in 후보_원인],
                "까닭": f"경보 패턴 {경보_패턴}가 떴는데 후보 원인 {len(후보_원인)}건이 모두 해당_없음.",
                "요청": (f"아님인 증거를 다시 확인: {', '.join(_증거_글(e) for e in 증거들)}."
                       " 한 원인의 증거가 모두 맞음으로 바뀌면 그 원인은 확인됨,"
                       " 일부만 바뀌면 가설(증거가 갈림)."),
            },
            "표제": f"후보 원인 {len(후보_원인)}건이 모두 해당_없음",
            "근거": [_근거(e) for e in 증거들],
            "원인들": list(후보_원인),
        })
    return 갈린_원인, 모두_해당_없음


def 사례_처리(사례, 허용):
    번호 = 사례["번호"]
    호출기 = 호출(허용)

    # 후보 모으기: 원인이 없는 고장 유형은 지나가고, 같은 원인은 한 번만 적는다
    후보 = 호출기.부르기("원인_후보", 패턴_코드=사례["경보_패턴"])
    원인들 = {}
    원인의_고장_유형 = {}
    for 고장 in 후보["고장_유형"]:
        for 원인 in 고장["원인"]:
            원인들.setdefault(원인["id"], 원인)
            원인의_고장_유형.setdefault(원인["id"], []).append(고장["id"])

    # 센서 값을 읽는 도구가 목록에 없거나 신선도가 한도를 넘으면 증거는 모두 확인하지 못한다
    도구_있음 = 호출기.있음("센서_집계")
    신선도 = None
    신선함 = False
    if 도구_있음:
        신선도 = (호출기.부르기("센서_집계", 사례=번호) or {}).get("freshness") or {}
        신선함 = 신선도.get("ok") is True

    후보_원인 = []
    사전_확률 = {}
    못_읽은_까닭 = {}  # (원인, 증거) → 까닭
    for 원인 in 원인들.values():
        증거 = []
        for 기준 in 호출기.부르기("증거_기준", 원인_식별자=원인["id"])["증거"]:
            판정, 값 = _증거_판정(호출기, 번호, 기준, 신선함)
            증거.append({
                "증거": 기준["id"],
                "판정": 판정,
                "읽은_값": 값,
                "기준": {k: 기준[k] for k in
                       ("tag", "aggregate", "windowSeconds", "expect", "threshold", "section")},
            })
            if 판정 == "확인하지_못함":
                # 신선할 때는 방금 부른 센서_집계가 돌려준 것이 기록의 마지막에 있다
                받음 = 호출기.기록[-1]["받음"] if 신선함 else None
                못_읽은_까닭[(원인["id"], 기준["id"])] = _못_읽은_까닭(도구_있음, 신선도, 받음)
        사전_확률[원인["id"]] = 원인["prior"]
        후보_원인.append({
            "원인": 원인["id"],
            "이름": 원인["name"],
            "구분": _구분([e["판정"] for e in 증거]),
            "증거": 증거,
        })

    # 확인됨 → 가설 → 해당_없음, 묶음 안에서는 사전 확률이 큰 순서(같으면 온톨로지에 적힌 순서)
    후보_원인.sort(key=lambda c: (_구분_순서[c["구분"]], -사전_확률[c["원인"]]))

    # 조치 방법은 후보 원인이 나온 고장 유형마다 묻는다
    받은_조치 = {}
    if 호출기.있음("조치_방법"):
        for 고장 in 후보["고장_유형"]:
            if 고장["원인"]:
                받은_조치[고장["id"]] = 호출기.부르기(
                    "조치_방법", 고장_유형_식별자=고장["id"])["조치"]

    def 사실(원인):
        return _사실_글(원인, 사전_확률[원인["원인"]])

    def 걸린_원인(원인들):
        return "; ".join(f"{_원인_글(c)} {사실(c)}" for c in 원인들) or "없음"

    부족 = _부족_확인(사례["경보_패턴"], 후보, 후보_원인, 못_읽은_까닭, 신선도)
    # 부족을 푸는 추가 확인끼리는 걸린 원인의 가장 큰 사전 확률이 큰 순서(같으면 처음 나온 순서)
    부족.sort(key=lambda b: -max((사전_확률[c["원인"]] for c in b["원인들"]), default=0))
    충돌, 모두_해당_없음 = _충돌_확인(사례["경보_패턴"], 후보_원인)
    추가_확인 = [b["항목"] for b in 부족 + 충돌 + 모두_해당_없음]
    상황들 = {항목["상황"] for 항목 in 추가_확인}

    # 신선도가 한도를 넘었거나 읽는 도구가 없는 사례는 원인 점검 줄을 내지 않는다
    원인_줄_없음 = any(b["사례에_한_건"] for b in 부족)
    점검 = []
    for b in 부족:
        사실_글 = f"걸린 원인: {걸린_원인(b['원인들'])}."
        if b["사례에_한_건"]:
            사실_글 += " 이 사례는 원인 점검 줄을 내지 않는다."
        elif b["증거_없음"]:
            사실_글 += " 등록된 증거가 없는 원인은 점검 줄을 내지 않는다."
        점검.append({
            "점검": {"내용": f"추가 확인(부족): {b['표제']}", "조치": []},
            "근거": b["근거"],
            "묶음": "부족을 푸는 추가 확인",
            "묶음_안": "걸린 원인의 가장 큰 사전 확률이 큰 순서다",
            "사실": 사실_글,
        })
    충돌인_원인 = {id(c) for b in 충돌 for c in b["원인들"]}
    묶음들 = (
        ("확인된 원인", "확인된 원인",
         [c for c in 후보_원인 if c["구분"] == "확인됨"]),
        ("충돌인 가설", "증거가 맞음과 아님으로 갈린(충돌) 원인",
         [c for c in 후보_원인 if id(c) in 충돌인_원인]),
        ("가설인 원인", "그 밖의 가설",
         [c for c in 후보_원인
          if c["구분"] == "가설" and id(c) not in 충돌인_원인 and c["증거"]]),
    )
    for 머리, 묶음, 묶인_원인 in () if 원인_줄_없음 else 묶음들:
        for 원인 in 묶인_원인:
            점검.append({
                "점검": {
                    "내용": f"{머리} 점검: {_원인_글(원인)}",
                    "조치": _붙일_조치(원인["원인"], 원인["구분"],
                                   원인의_고장_유형[원인["원인"]], 받은_조치),
                },
                "근거": [_근거(e) for e in 원인["증거"]],
                "묶음": 묶음,
                "묶음_안": "사전 확률이 큰 순서다",
                "사실": f"{사실(원인)}.",
            })
    for b in 모두_해당_없음:
        점검.append({
            "점검": {"내용": f"추가 확인(충돌): {b['표제']}", "조치": []},
            "근거": b["근거"],
            "묶음": "후보 원인이 모두 해당_없음이어서 원인 점검 줄 대신 내는 추가 확인",
            "묶음_안": "",
            "사실": f"걸린 원인: {걸린_원인(b['원인들'])}.",
        })

    # 까닭의 첫 문장은 이 사례의 점검 순서에서 실제로 앞에 놓인 줄만 든다
    점검_순서 = []
    for 순번, p in enumerate(점검, 1):
        앞 = 점검[순번 - 2] if 순번 > 1 else None
        if 앞 is None:
            놓은_까닭 = f"{p['묶음']}이며 이 사례의 첫 점검이다."
        elif 앞["묶음"] != p["묶음"]:
            놓은_까닭 = f"{p['묶음']}이어서 앞의 {순번 - 1}번({앞['묶음']}) 다음에 둔다."
        else:
            놓은_까닭 = (f"{p['묶음']}이며 같은 묶음의 {순번 - 1}번 다음에 둔다."
                      f" 묶음 안에서는 {p['묶음_안']}.")
        점검_순서.append({"순번": 순번, "점검": p["점검"], "근거": p["근거"],
                      "까닭": f"{놓은_까닭} {p['사실']}"})

    return {
        "번호": 번호,
        "근거_상태": _근거_상태([c["구분"] for c in 후보_원인]),
        "후보_원인": 후보_원인,
        "증거_상황": ("부족과_충돌" if 상황들 == {"부족", "충돌"}
                  else "부족" if "부족" in 상황들 else "충돌" if "충돌" in 상황들 else "충분"),
        "추가_확인": 추가_확인,
        "점검_순서": 점검_순서,
        "호출_기록": 호출기.기록,
    }


def _글(값):
    return json.dumps(값, ensure_ascii=False)


def _기준_글(기준):
    return (f"{기준['aggregate']}({기준['tag']}) {기준['windowSeconds']}초 "
            f"{기준['expect']} {_글(기준['threshold'])} · 근거 절 {_글(기준['section'])}")


def 마크다운(결과들):
    줄 = ["# 점검 계획", ""]
    for 결과 in 결과들:
        줄 += [f"## {결과['번호']}", "", f"**근거 상태: {결과['근거_상태']}**", "",
              f"**증거 상황: {결과['증거_상황']}**", ""]
        for 구분, 제목 in (("확인됨", "확인된 원인"), ("가설", "가설"), ("해당_없음", "해당 없음")):
            줄 += [f"### {제목}", ""]
            원인들 = [c for c in 결과["후보_원인"] if c["구분"] == 구분]
            if not 원인들:
                줄 += ["없음", ""]
                continue
            for 원인 in 원인들:
                줄.append(f"- {원인['이름']} (`{원인['원인']}`)")
                if not 원인["증거"]:
                    줄.append("  - 증거: 없음")
                for e in 원인["증거"]:
                    줄.append(f"  - `{e['증거']}`: {e['판정']} · 읽은 값 {_글(e['읽은_값'])}"
                             f" · 기준 {_기준_글(e['기준'])}")
            줄.append("")
        줄 += ["### 추가 확인", ""]
        if not 결과["추가_확인"]:
            줄.append("없음")
        for 항목 in 결과["추가_확인"]:
            줄.append(f"- [{항목['상황']}] 대상: "
                     + (", ".join(f"`{d}`" for d in 항목["대상"]) or "없음"))
            줄.append(f"  - 까닭: {항목['까닭']}")
            줄.append(f"  - 요청: {항목['요청']}")
        줄 += ["", "### 점검 순서", ""]
        # 조치의 단계 전체는 호출 기록에 받아 둔 것에서 찾는다
        단계들 = {
            조치["sopId"]: 조치["steps"]
            for 호출_한_건 in 결과["호출_기록"] if 호출_한_건["도구"] == "조치_방법"
            for 조치 in 호출_한_건["받음"]["조치"]
        }
        if not 결과["점검_순서"]:
            줄.append("없음")
        for 점검 in 결과["점검_순서"]:
            줄.append(f"{점검['순번']}. {점검['점검']['내용']}")
            줄.append(f"   - 까닭: {점검['까닭']}")
            for g in 점검["근거"]:
                줄.append(f"   - 근거: `{g['증거']}` · 읽은 값 {_글(g['읽은_값'])}"
                         f" · 근거 절 {_글(g['근거_절'])}")
            for j in 점검["점검"]["조치"]:
                첫 = j["첫_단계"] or {}
                금지_단계 = [s for s in 단계들.get(j["절차_번호"], [])
                         if "금지" in (s.get("text") or "")]
                표시 = "[단계에 금지 문구 있음 · 원문 확인] " if 금지_단계 else ""
                줄.append(f"   - {표시}[{j['시점']}] {j['절차_번호']} {j['이름']} · {j['종류']}"
                         f" · 첫 단계 {_글(첫.get('글'))} (근거 절 {_글(첫.get('근거_절'))})"
                         f" · 승인 역할 {j['승인_역할']}")
                for s in 금지_단계:
                    줄.append(f"     - 금지 문구가 있는 단계 {s.get('order')}: {_글(s.get('text'))}"
                             f" (근거 절 {_글(s.get('section'))})")
        줄 += ["", "### 호출 기록", ""]
        for i, 호출_한_건 in enumerate(결과["호출_기록"], 1):
            줄.append(f"{i}. `{호출_한_건['도구']}` 물음 `{_글(호출_한_건['물음'])}`")
            줄.append(f"   - 받음: `{_글(호출_한_건['받음'])}`")
        줄.append("")
    return "\n".join(줄)


def _못_읽은_까닭(도구_있음, 신선도, 받음):
    """확인하지 못한 증거 한 건의 까닭. 앞에서부터 먼저 걸리는 하나만 낸다."""
    if not 도구_있음:
        return "읽는 도구 없음"
    if not 신선도:
        return "값 없음"
    if 신선도.get("ok") is not True:
        return "신선도 초과"
    if (받음 or {}).get("value") is None:
        return "값 없음"
    return "관측 공백 초과"


def _칸(글들):
    return "<br>".join(글들).replace("|", "\\|") if 글들 else "없음"


def 증거_비교(결과들):
    줄 = ["# 증거 비교", ""]
    for 결과 in 결과들:
        # 신선도와 비교하지 않은 값은 호출 기록에 받아 둔 것에서 찾는다
        집계_호출 = [h for h in 결과["호출_기록"] if h["도구"] == "센서_집계"]
        도구_있음 = bool(집계_호출)
        신선도 = next(((h["받음"] or {}).get("freshness")
                    for h in 집계_호출 if "tag" not in h["물음"]), None)
        받은_값 = {
            (h["물음"]["tag"], h["물음"]["aggregate"], h["물음"]["windowSeconds"]): h["받음"] or {}
            for h in 집계_호출 if "tag" in h["물음"]
        }
        줄 += [f"## {결과['번호']}", "",
              "| 원인 | 구분 | 맞는 증거 | 맞지 않는 증거 | 확인하지 못한 증거 |",
              "|---|---|---|---|---|"]
        for 원인 in 결과["후보_원인"]:
            칸 = {"맞음": [], "아님": [], "확인하지_못함": []}
            for e in 원인["증거"]:
                기준 = e["기준"]
                if e["판정"] != "확인하지_못함":
                    칸[e["판정"]].append(
                        f"`{e['증거']}` 읽은 값 {_글(e['읽은_값'])} · 기준 {_기준_글(기준)}")
                    continue
                받음 = 받은_값.get((기준["tag"], 기준["aggregate"], 기준["windowSeconds"]), {})
                관측 = 받음.get("coverage") or {}
                까닭 = _못_읽은_까닭(도구_있음, 신선도, 받음)
                if 까닭 == "신선도 초과":
                    까닭 += (f" (최신 {신선도.get('tag')} 값의 나이 {_글(신선도.get('age_s'))}초"
                           f" · 한도 {_글(신선도.get('max_age_s'))}초)")
                elif 까닭 == "관측 공백 초과":
                    까닭 += (f" (받은 값 {_글(받음.get('value'))}, 비교하지 않음"
                           f" · 가장 긴 공백 {_글(관측.get('max_gap_s'))}초"
                           f" · 한도 {_글(관측.get('limit_s'))}초)")
                elif 까닭 == "값 없음" and not 신선도:
                    까닭 += " (신선도를 받지 못함)"
                elif 까닭 == "값 없음":
                    까닭 += (f" (받은 값 {_글(받음.get('value'))}"
                           f" · 구간에 들어온 값 {_글(관측.get('samples'))}건)")
                칸["확인하지_못함"].append(f"`{e['증거']}` {까닭} · 기준 {_기준_글(기준)}")
            if not 원인["증거"]:
                칸["확인하지_못함"].append("등록된 증거 없음")
            줄.append(f"| {원인['이름']} (`{원인['원인']}`) | {원인['구분']} | {_칸(칸['맞음'])}"
                     f" | {_칸(칸['아님'])} | {_칸(칸['확인하지_못함'])} |")
        if not 결과["후보_원인"]:
            줄 += ["", "등록된 원인 없음"]
        줄.append("")
    return "\n".join(줄)


def main(인자):
    if len(인자) > 1:
        raise SystemExit("쓰는 법: python 에이전트.py [사례 번호]")
    허용 = _읽기(_정의_경로)["도구"]
    사례들 = _읽기(_입력_경로)
    if 인자:
        사례들 = [s for s in 사례들 if s["번호"] == 인자[0]]
        if not 사례들:
            raise SystemExit(f"입력에 없는 사례 번호: {인자[0]}")

    결과들 = [사례_처리(사례, 허용) for 사례 in 사례들]

    with open(_결과_폴더 / "점검_계획.json", "w", encoding="utf-8") as f:
        json.dump(결과들, f, ensure_ascii=False, indent=2)
        f.write("\n")
    with open(_결과_폴더 / "점검_계획.md", "w", encoding="utf-8") as f:
        f.write(마크다운(결과들))
    with open(_결과_폴더 / "증거_비교.md", "w", encoding="utf-8") as f:
        f.write(증거_비교(결과들))


