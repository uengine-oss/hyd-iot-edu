#!/usr/bin/env bash
# 대화가 요약(compact)된 직후 실행된다. 요약은 기준을 일부만 남기므로, 기억이 아니라 문서로 돌아가게 한다(열화 · 누락 방지).
cd "${CLAUDE_PROJECT_DIR:-.}" || exit 0
echo "[요약 직후 — 작업을 잇기 전에 반드시]"
echo "대화가 요약됐다. 요약은 기준의 일부만 남긴다. 다음을 하기 전에는 하던 작업을 잇지 않는다."
open=0
for d in 작업/[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]_*/; do
  [ -d "$d" ] || continue
  st=$(grep -m1 -o '상태: *[^ ]*' "$d/스펙.md" 2>/dev/null | sed 's/상태: *//')
  echo "- 열린 작업: ${d%/} (상태 ${st:-스펙 없음})"
  open=$((open+1))
done
[ "$open" -eq 0 ] && echo "- 열린 작업 폴더 없음"
cat <<'EOF'
1. 하던 작업 폴더의 스펙.md · 기록.md를 다시 읽는다.
2. 그 스펙이 가리키는 문서 하나를 처음부터 끝까지 다시 읽는다 — 강의 제작이면 `workspace/강의제작/지침/`의 산출물 문서(촬영이면 그 도구의 `workspace/강의제작/제작도구/촬영/<도구>/촬영준비.md`도), 시스템 개발이면 `workspace/개발/문서/`의 그 문서.
3. git 상태와 기록.md의 차이를 확인한다. 요약에 적힌 「완료」 「확인됨」은 실제 파일 · 숫자로 다시 확인하기 전에는 믿지 않는다.
EOF
exit 0
