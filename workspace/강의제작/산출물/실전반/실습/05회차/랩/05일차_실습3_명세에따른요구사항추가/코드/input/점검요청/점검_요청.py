def _증거_판정(사례, 기준):
    """증거 한 건의 (판정, 읽은 값, 확인하지 못한 까닭)."""
    if (사례.get("freshness") or {}).get("ok") is not True:
        return "확인하지_못함", None, "신선도 실패(최신 TS1 값이 한도보다 오래됨)"
    읽음 = 도구.센서_집계(사례, 기준["tag"], 기준["aggregate"], 기준["windowSeconds"])
    값 = 읽음.get("value")
    관측 = 읽음.get("coverage") or {}
    if 값 is None:
        return "확인하지_못함", None, "값 없음"
    if 관측.get("covered") is not True:
        return "확인하지_못함", 값, f"표본 부족(공백 {관측.get('max_gap_s')}초 > 한도 {관측.get('limit_s')}초)"
    return ("맞음" if _비교[기준["expect"]](값, 기준["threshold"]) else "아님"), 값, None


def _구분(판정들):
    if 판정들 and all(p == "맞음" for p in 판정들):
        return "확인됨"
    if 판정들 and all(p == "아님" for p in 판정들):
        return "해당_없음"
    return "가설"


def _근거_상태(구분들):
    if any(g == "확인됨" for g in 구분들):
        return "SUPPORTED"
    if 구분들 and all(g == "해당_없음" for g in 구분들):
        return "UNSUPPORTED"
    return "UNKNOWN"


def _기준_글(기준):
    return (f"{기준['aggregate']}({기준['tag']}) {기준['windowSeconds']}초 "
            f"{_비교_글[기준['expect']]} {기준['threshold']}")


def 초안을_만든다(사례, 자료_):
    """사례 한 건 → 점검 요청 초안(대상 설비 · 부품 · 관측 시각 · 확인 항목 · 이유)."""
    g = 자료_.그래프
    후보 = 도구.원인_후보(g, 사례["경보_패턴"])
    원인들, 원인의_고장 = {}, {}
    for 고장 in 후보["고장_유형"]:
        for 원인 in 고장["원인"]:
            원인들.setdefault(원인["id"], 원인)
            원인의_고장.setdefault(원인["id"], []).append(고장)

    후보_원인, 다시_확인 = [], {}
    for 원인 in 원인들.values():
        증거 = []
        for 기준 in 도구.증거_기준(g, 원인["id"]):
            판정, 값, 까닭 = _증거_판정(사례, 기준)
            증거.append({"증거": 기준["id"], "이름": 기준["name"], "판정": 판정, "읽은_값": 값,
                       "기준": _기준_글(기준), "근거_절": 기준["section"], "확인하지_못한_까닭": 까닭})
            if 판정 == "확인하지_못함":
                다시_확인.setdefault((기준["tag"], 기준["aggregate"], 기준["windowSeconds"]), 까닭)
        후보_원인.append({"원인": 원인["id"], "이름": 원인["name"], "사전_확률": 원인["prior"],
                      "근거_절": 원인["section"], "구분": _구분([e["판정"] for e in 증거]), "증거": 증거})
    후보_원인.sort(key=lambda c: (_구분_순서[c["구분"]], -(c["사전_확률"] or 0)))
    살아_있는 = [c for c in 후보_원인 if c["구분"] != "해당_없음"]

    구성_요소, 부품 = [], []
    for c in 살아_있는:
        for 고장 in 원인의_고장[c["원인"]]:
            for 이름 in 고장["구성_요소"]:
                if 이름 not in 구성_요소:
                    구성_요소.append(이름)
        for p in 도구.관련_부품(자료_.매뉴얼, 원인들[c["원인"]]):
            부품.append({**p, "원인": c["이름"]})

    확인_항목 = [f"값 다시 확인: {태그} {집계} {구간}초 — {까닭}" for (태그, 집계, 구간), 까닭 in 다시_확인.items()]
    for c in 살아_있는:
        절 = c["근거_절"] or "근거 절 없음"
        if c["구분"] == "확인됨":
            확인_항목.append(f"현장 확인: {c['이름']} — 등록 증거 {len(c['증거'])}건이 모두 맞음({절})")
        elif not c["증거"]:
            확인_항목.append(f"추가 확인: {c['이름']} — 등록된 증거가 없어 센서 값으로 가릴 수 없음({절})")
        else:
            남은 = [e["증거"] for e in c["증거"] if e["판정"] != "맞음"]
            확인_항목.append(f"추가 확인: {c['이름']} — 맞지 않거나 확인하지 못한 증거 {', '.join(남은)}({절})")
    if 후보_원인 and not 살아_있는:
        확인_항목.append("현장 직접 확인: 등록된 원인 후보의 기준에 맞는 것이 없음")

    이유 = []
    for c in 후보_원인:
        for e in c["증거"]:
            이유.append(f"{c['이름']}({c['구분']}): {e['이름']} — 기준 {e['기준']}, 읽은 값 "
                      f"{json.dumps(e['읽은_값'])} → {e['판정']}"
                      + (f"({e['확인하지_못한_까닭']})" if e["확인하지_못한_까닭"] else "")
                      + f" [{e['근거_절'] or '근거 절 없음'}]")
        if not c["증거"]:
            이유.append(f"{c['이름']}({c['구분']}): 등록된 증거 없음")

    조치 = []
    for c in 살아_있는:
        for 고장 in 원인의_고장[c["원인"]]:
            for j in 도구.조치_방법(g, 고장["id"]):
                if j["맞는_원인"] and c["원인"] not in j["맞는_원인"]:
                    continue
                if c["구분"] == "가설" and j["관계"] != "REMEDIED_BY":
                    continue
                if any(x["절차_번호"] == j["sopId"] for x in 조치):
                    continue
                금지 = [s.get("text") for s in j["steps"] if "금지" in (s.get("text") or "")]
                조치.append({"절차_번호": j["sopId"], "이름": j["name"], "종류": _조치_종류[j["관계"]],
                           "원인": c["이름"], "승인_역할": (j["승인_역할"] or {}).get("name"),
                           "금지_문구": 금지})

    return {
        "구분": "점검 요청 초안 · 작업지시 아님",
        "대상_설비": 사례["설비"],
        "경보_패턴": 사례["경보_패턴"],
        "구성_요소": 구성_요소,
        "부품": 부품,
        "관측_시각": 사례["판단_시각"],
        "신선도": 사례.get("freshness"),
        "근거_상태": _근거_상태([c["구분"] for c in 후보_원인]),
        "원인_후보": 후보_원인,
        "확인_항목": 확인_항목,
        "이유": 이유,
        "조치": 조치,
    }


# ── 승인 기록 ────────────────────────────────────────────────────────────

def _승인할_수_있다(g, 역할_노드, 조치_한_건):
    """같은 역할이거나 그 조치의 승인 역할보다 높은 등급이면 승인할 수 있다."""
    if not 조치_한_건["승인_역할"] or 조치_한_건["금지_문구"]:
        return False
    필요 = 도구.역할(g, 조치_한_건["승인_역할"])
    return 역할_노드["name"] == 필요["name"] or 역할_노드["level"] > 필요["level"]


def 결정_반영(결과, 자료_):
    """승인.json에서 이 요청 번호의 결정만 읽어 반영한다. 승인 대기가 아니면 반영하지 않는다."""
    g = 자료_.그래프
    for 결정 in [d for d in 자료_.결정들 if d.get("요청") == 결과["요청"]]:
        글 = json.dumps(결정, ensure_ascii=False)
        if 결과["상태"] != "승인 대기":
            _기록(결과, 결과["상태"], f"결정 {글}을 반영하지 않음: 상태가 승인 대기가 아님")
            continue
        역할_노드 = 도구.역할(g, 결정.get("역할"))
        if 역할_노드 is None:
            _기록(결과, 결과["상태"], f"결정 {글}을 반영하지 않음: 온톨로지에 없는 역할")
            continue
        조치 = 결과["초안"]["조치"]
        if 결정.get("결정") == "승인":
            고른 = next((j for j in 조치 if j["절차_번호"] == 결정.get("절차_번호")), None)
            if 고른 is None:
                _기록(결과, 결과["상태"], f"결정 {글}을 반영하지 않음: 초안의 조치에 없는 절차")
            elif not _승인할_수_있다(g, 역할_노드, 고른):
                _기록(결과, 결과["상태"], f"결정 {글}을 반영하지 않음: 승인 역할({고른['승인_역할'] or '등록되지 않음'})"
                      f"{' · 금지 문구가 있는 절차' if 고른['금지_문구'] else ''}을 충족하지 않음")
            else:
                결과["승인"] = {k: 결정.get(k) for k in ("결정", "절차_번호", "역할", "이름", "사유")}
                결과["후속_업무"] = [{"절차_번호": 고른["절차_번호"],
                                  "내용": "승인된 조치의 실행 요청 대상(이 프로그램은 설비 명령 · 작업지시를 만들지 않음)"}]
                _기록(결과, "승인됨", f"승인: {결정.get('역할')} {결정.get('이름')} · {고른['절차_번호']}")
        elif 결정.get("결정") == "거절":
            if not (결정.get("사유") or "").strip():
                _기록(결과, 결과["상태"], f"결정 {글}을 반영하지 않음: 거절 사유가 없음")
            elif not any(_승인할_수_있다(g, 역할_노드, j) for j in 조치):
                _기록(결과, 결과["상태"], f"결정 {글}을 반영하지 않음: 이 요청의 조치를 결정할 역할이 아님")
            else:
                결과["승인"] = {k: 결정.get(k) for k in ("결정", "절차_번호", "역할", "이름", "사유")}
                결과["후속_업무"] = []
                _기록(결과, "거절", f"거절: {결정.get('역할')} {결정.get('이름')} · 사유 {결정['사유']}")
        else:
            _기록(결과, 결과["상태"], f"결정 {글}을 반영하지 않음: 결정은 승인 또는 거절")


