"""점검 요청 기능. 요청의 설비 · 경보 · 사례를 기존 자료로 먼저 확인하고, 정할 수 없거나 어긋난 정보만 묻는다.
답(사람/답변.json)은 같은 요청 번호 · 같은 질문 순번에만 이어 다시 판단한다. 사례 한 건으로 점검 요청 초안을
만들고, 사람의 승인 기록(사람/승인.json)을 반영한다. 답변은 정보이며 승인이 아니다.

    python 점검_요청.py               원자료의 요청 전부
    python 점검_요청.py R03           그 요청만
    python 점검_요청.py --원자료 <source 폴더> --입력 <폴더> --사람 <폴더> --결과 <폴더>

기본 원자료는 이 폴더의 두 단계 위 `source/`, 결과는 이 폴더의 `결과/`다.
초안은 점검 요청 초안이며 작업지시가 아니다. 이 프로그램은 설비 명령 · 작업지시를 만들지 않는다.
"""
from __future__ import annotations

import json
import operator
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # __pycache__를 만들지 않는다

import 도구  # noqa: E402

_폴더 = Path(__file__).resolve().parent
_기본_원자료 = _폴더.parent.parent / "source"

_비교 = {"lt": operator.lt, "gt": operator.gt, "gte": operator.ge}
_비교_글 = {"lt": "<", "gt": ">", "gte": ">="}
_구분_순서 = {"확인됨": 0, "가설": 1, "해당_없음": 2}
_조치_종류 = {"MITIGATED_BY": "즉시_완화", "REMEDIED_BY": "근본_조치"}


class 자료:
    """한 번 실행에서 쓰는 원자료. 센서 사례는 물을 때마다 파일에서 읽는다(도구)."""

    def __init__(self, 원자료: Path = _기본_원자료, 입력: Path | None = None, 사람: Path | None = None):
        원자료 = Path(원자료)
        입력 = Path(입력) if 입력 else 원자료 / "입력"
        사람 = Path(사람) if 사람 else 원자료 / "사람"
        self.그래프 = 도구.그래프(원자료 / "온톨로지" / "graph.json")
        self.매뉴얼 = 원자료 / "매뉴얼"
        self.요청들 = 도구._json(입력 / "점검_요청.json")
        self.센서_경로 = 입력 / "센서_입력.json"
        self.결정들 = 도구._json(사람 / "승인.json") if (사람 / "승인.json").exists() else []
        self.답변들 = 도구._json(사람 / "답변.json") if (사람 / "답변.json").exists() else []

    def 사례(self, 번호):
        return 도구.센서_사례(self.센서_경로, 번호)

    def 사례_목록(self):
        return 도구.센서_사례_목록(self.센서_경로)


def _기록(결과, 상태, 까닭):
    결과["상태"] = 상태
    결과["상태_기록"].append({"순번": len(결과["상태_기록"]) + 1, "상태": 상태, "까닭": 까닭})


def _보류(결과, 사유):
    결과["보류_사유"] = 사유
    _기록(결과, "보류", 사유)


