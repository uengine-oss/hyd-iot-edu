def _사례_글(s):
    return f"{s['번호']}(설비 {s['설비']}, 경보 {s['경보_패턴']}, 판단 시각 {s['판단_시각']})"


def _질문(결과, 자료_, 물음, 선택지):
    """질문 한 건을 내고, 같은 요청 번호 · 같은 순번의 답만 찾아 돌려준다. 답이 없거나 선택지 밖이면 None."""
    순번 = len(결과["질문"]) + 1
    질문 = {"순번": 순번, "물음": 물음, "선택지": 선택지, "답": None, "답한_사람": None, "반영": "답 대기"}
    결과["질문"].append(질문)
    같은_질문 = [a for a in 자료_.답변들 if a.get("요청") == 결과["요청"] and a.get("질문") == 순번]
    받은 = 같은_질문[0] if 같은_질문 else None
    for 뒤의 in 같은_질문[1:]:  # 답은 한 번만 받는다
        _기록(결과, 결과["상태"], f"답 {_글(뒤의)}을 반영하지 않음: 질문 {순번}에는 이미 답이 있음")
    if 받은 is None:
        _기록(결과, "질문 대기", f"질문 {순번}을 냄")
        return None
    질문["답"], 질문["답한_사람"] = 받은.get("답"), 받은.get("답한_사람")
    if 받은.get("답") not in 선택지:
        질문["반영"] = "선택지에 없는 답이라 반영하지 않음(답변은 정보만 채우고 승인이 아님)"
        _기록(결과, "질문 대기", f"질문 {순번}의 답 {_글(받은.get('답'))}을 반영하지 않음: 선택지 밖")
        return None
    질문["반영"] = "반영함"
    _기록(결과, "재개", f"질문 {순번}의 답 {받은['답']}({받은.get('답한_사람')})을 같은 요청에 반영")
    return 받은["답"]


def _사례_정하기(요청, 결과, 자료_):
    """기존 자료로 먼저 사례를 정하고, 정할 수 없거나 어긋날 때만 묻는다. 정한 사례(dict) 또는 None."""
    설비, 경보, 번호 = 요청.get("설비"), 요청.get("경보_패턴"), 요청.get("사례")
    목록 = 자료_.사례_목록()
    if 번호:
        사례 = 자료_.사례(번호)
        if 사례 is None:
            _보류(결과, f"사례 {번호}가 센서 입력에 없음")
            return None
        어긋남 = [f"{칸} {요청[칸]} ≠ 사례의 {사례[칸]}" for 칸 in ("설비", "경보_패턴")
                if 요청.get(칸) is not None and 요청[칸] != 사례[칸]]
        if not 어긋남:
            결과["사례_확인"].append(f"요청에 적힌 사례 {_사례_글(사례)}")
            for 칸 in ("설비", "경보_패턴"):
                if 요청.get(칸) is None:
                    결과["사례_확인"].append(f"요청에 없던 {칸} 값을 사례에서 확인: {사례[칸]}")
            return 사례
        결과["사례_확인"].append(f"요청과 사례가 어긋남: {' · '.join(어긋남)}")
        다른 = [s for s in 목록 if s["번호"] != 번호
               and (설비 is None or s["설비"] == 설비) and (경보 is None or s["경보_패턴"] == 경보)]
        선택지 = [번호] + [s["번호"] for s in 다른]
        답 = _질문(결과, 자료_, f"요청의 {' · '.join(어긋남)}입니다. 어느 사례를 처리할까요? "
                   + " / ".join(_사례_글(s) for s in [사례, *다른]), 선택지)
        if 답 is None:
            결과["보류_사유"] = f"질문 {len(결과['질문'])}의 답을 기다림: 요청과 사례가 어긋남"
            return None
        결과["사례_확인"].append(f"질문 {len(결과['질문'])}의 답으로 사례를 {답}(으)로 정함 — 원 요청의 사례 {번호}")
        return 자료_.사례(답)

    후보 = [s for s in 목록 if (설비 is None or s["설비"] == 설비) and (경보 is None or s["경보_패턴"] == 경보)]
    if not 후보:
        _보류(결과, f"요청의 설비 {설비} · 경보 {경보}에 맞는 사례가 센서 입력에 없음 — 경보 기록부터 확인")
        return None
    while len(후보) > 1:
        설비들 = sorted({s["설비"] for s in 후보})
        if 설비 is None and len(설비들) > 1:
            답 = _질문(결과, 자료_, "요청에 설비가 적혀 있지 않습니다. 대상 설비를 골라 주세요. "
                       f"맞는 사례 {len(후보)}건이 {', '.join(설비들)}에 있습니다.", 설비들)
            if 답 is None:
                결과["보류_사유"] = f"질문 {len(결과['질문'])}의 답을 기다림: 대상 설비"
                return None
            설비 = 답
            후보 = [s for s in 후보 if s["설비"] == 설비]
            결과["사례_확인"].append(f"질문 {len(결과['질문'])}의 답으로 설비를 {설비}(으)로 정함")
            continue
        답 = _질문(결과, 자료_, "요청에 사례가 적혀 있지 않고 맞는 사례가 여럿입니다. 어느 경보 건인가요? "
                   + " / ".join(_사례_글(s) for s in 후보), [s["번호"] for s in 후보])
        if 답 is None:
            결과["보류_사유"] = f"질문 {len(결과['질문'])}의 답을 기다림: 경보 건(사례)"
            return None
        결과["사례_확인"].append(f"질문 {len(결과['질문'])}의 답으로 사례를 {답}(으)로 정함")
        return 자료_.사례(답)
    결과["사례_확인"].append(f"기존 자료로 확인: 요청의 설비 {설비} · 경보 {경보}에 맞는 사례가 하나 — {_사례_글(후보[0])}")
    return 자료_.사례(후보[0]["번호"])


def 처리한다(요청, 자료_):
    """점검 요청 한 건 → 결과(상태 · 보류_사유 · 사례 · 사례_확인 · 질문 · 초안 · 확인_항목_변화 · 승인 · 후속_업무 · 상태_기록)."""
    결과 = {"요청": 요청["번호"], "상태": "접수", "보류_사유": None, "사례": None, "사례_확인": [], "질문": [],
           "초안": None, "확인_항목_변화": [], "승인": None, "후속_업무": [], "상태_기록": []}
    _기록(결과, "접수", "요청을 받음")
    사례 = _사례_정하기(요청, 결과, 자료_)
    받은_답 = [q for q in 결과["질문"] if q["반영"] == "반영함"]
    내지_않은 = [a for a in 자료_.답변들
              if a.get("요청") == 결과["요청"] and a.get("질문") not in [q["순번"] for q in 결과["질문"]]]
    for a in 내지_않은:
        _기록(결과, 결과["상태"], f"답 {_글(a)}을 반영하지 않음: 이 요청에서 내지 않은 질문 순번")
    if 사례 is not None:
        결과["사례"] = 사례["번호"]
        초안 = 초안을_만든다(사례, 자료_)
        결과["초안"] = 초안
        if 결과["질문"]:
            결과["확인_항목_변화"] = [
                {"시점": "답변 전", "사례": None, "확인_항목": []},
                {"시점": f"질문 {받은_답[-1]['순번']} 답변 뒤", "사례": 사례["번호"], "확인_항목": 초안["확인_항목"]},
            ]
        근거 = 초안["근거_상태"]
        if 근거 == "SUPPORTED":
            _기록(결과, "승인 대기", f"사례 {사례['번호']}의 점검 요청 초안을 만듦 · 근거 상태 {근거}")
        elif 근거 == "UNSUPPORTED":
            _보류(결과, f"근거 상태 {근거}: 등록된 원인 기준에 맞는 것이 없어 현장 직접 확인 필요")
        else:
            _보류(결과, f"근거 상태 {근거}: 확인된 원인이 없음 — 초안의 확인 항목을 먼저 확인")
    결정_반영(결과, 자료_)
    return 결과


