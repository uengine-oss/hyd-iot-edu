"""관계조회 다시 찍을 판의 조작 표 — build_retake_cues.py가 읽는다.
RETAKE_OPS[구간] = [(큐 글 첫머리, 조작 | [조작, …]), …] 차례대로. 첫머리는 그 구간 큐 글의 시작과 같아야 한다(대본을 고쳐도 첫머리가 그대로면 짝이 유지된다).
조작 꼴은 record_graph_lesson.mjs의 doOp가 정한다. at = 그 큐 말 안의 비율(0~1)에서 한다. block = 안내 문서 칸 번호(1부터, 3이 첫 CREATE)."""

ED = '[aria-label="Cypher Editor"]'
TB = '[role="table"]'


def T(contains, at, within=None, **kw):
    return {'op': 'pointText', 'contains': contains, 'at': at, **({'within': within} if within else {}), **kw}


def E(contains, at):  # 입력칸 안 글 짚기
    return T(contains, at, ED)


def Q(block, at):
    return {'op': 'query', 'block': block, 'at': at}


def RG(nodes, edges, at=.95):
    return {'op': 'run', 'graph': True, 'nodes': nodes, 'edges': edges, 'rows': None, 'at': at}


def RT(rows, at=.95):
    return {'op': 'run', 'graph': False, 'nodes': None, 'edges': None, 'rows': rows, 'at': at}


def G(*pts):  # 그림의 원 짚기: (at, 이름) · (at, 이름, 'edge') · (at, (A, B)) = 두 원 사이
    out = []
    for p in pts:
        if isinstance(p[1], tuple):
            out.append({'between': list(p[1]), 'at': p[0]})
        else:
            out.append({'label': p[1], 'at': p[0], **({'edge': True} if len(p) > 2 else {})})
    return {'op': 'graphTalk', 'points': out}


def D(*pts):  # 정보 칸 글 짚기
    return {'op': 'detailsTour', 'points': [{'text': t, 'at': a} for a, t in pts]}


def NODE(label, verify, click_at=.9, **kw):
    return {'op': 'node', 'label': label, 'verify': verify, 'guided_focus': True, 'click_at': click_at, **kw}


def CLEAR(at=.85):
    return {'op': 'clear', 'at': at, 'enter_at': min(.98, at + .1)}


NONE = {'op': 'none'}


def RESULT(at=.15):
    return {'op': 'result', 'at': at}


