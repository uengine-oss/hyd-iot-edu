def main():
    plan = json.loads(PLAN.read_text(encoding='utf-8'))
    U = plan['단위']
    ids = {u['id'] for u in U}
    for k in set(새글) | 뺌 | 잇기 | 붙임앞 | 붙임뒤:
        if k not in ids: sys.exit(f'계획에 없는 단위 {k}')
    if 붙임앞 & 붙임뒤: sys.exit(f'붙임 앞과 뒤가 겹친다: {붙임앞 & 붙임뒤}')
    if set(새글) & 뺌: sys.exit(f'새 글과 뺌이 겹친다: {set(새글) & 뺌}')
    if 잇기 & 뺌: sys.exit(f'잇기와 뺌이 겹친다: {잇기 & 뺌}')
    if 'N-card-url' in 새글: sys.exit('N-card-url은 산 판이다 — 바꾸지 않는다')
    for md in MD:
        raw = md.read_bytes()
        if b'\r\n' in raw: sys.exit(f'{md}: CRLF다 — git 판(LF)으로 되돌린 뒤 돌린다')
        blocks = raw.decode('utf-8').split('\n\n')
        speech = [i for i, b in enumerate(blocks) if b.strip() and not b.lstrip().startswith(('>', '#'))]
        if len(speech) != len(U): sys.exit(f'{md}: 낭독 문단 {len(speech)} ≠ 계획 단위 {len(U)} — 게시본 판에서 시작한다')
        drop = set()
        for i, u in zip(speech, U):
            cur = blocks[i].strip()
            if cur != u['글'].strip() and u['id'] != 'N-card-url':
                sys.exit(f'{md}: {u["id"]} 문단이 게시본 글과 다르다 — 게시본 판에서 시작한다')
            if u['id'] in 뺌: drop.add(i)   # 뒤의 조작 줄은 남는다(말만 빼고 화면은 둔다)
            elif u['id'] in 새글: blocks[i] = 새글[u['id']]
        md.write_bytes('\n\n'.join(b for i, b in enumerate(blocks) if i not in drop).encode('utf-8'))
    head = json.loads((HERE / '노션_바꿀큐.json').read_text(encoding='utf-8'))
    card = {c['id']: c['text'] for c in head['cues']}
    cues = [{'id': u['id'], 'segment': 0, 'text': 새글.get(u['id'], card.get(u['id'], u['글']))} for u in U if u['id'] not in 뺌]
    CUES.write_text(json.dumps({'voice_id': head['voice_id'], 'model_id': head['model_id'], 'cues': cues}, ensure_ascii=False, indent=1) + '\n', encoding='utf-8', newline='\n')
    for u in U:
        if u['id'] in 잇기: u['쉼뒤'] = '잇기'
    plan['문장쉼'] = 0.5   # 새 음성 안 문장 사이(04와 같은 값 — 영상 V-14)
    PLAN.write_text(json.dumps(plan, ensure_ascii=False, indent=1) + '\n', encoding='utf-8', newline='\n')
    n = sum(len(v) for v in 새글.values())
    print(f'새 글 {len(새글)}단위 {n}자(견적 약 {n * 0.485:.0f}크레딧) · 뺌 {len(뺌)} · 잇기 {len(잇기)} · 큐 {len(cues)}')


if __name__ == '__main__':
    apply_attach() if sys.argv[1:] == ['--붙임'] else main()
