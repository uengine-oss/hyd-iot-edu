def apply_attach():
    plan = json.loads(PLAN.read_text(encoding='utf-8'))
    n = 0
    for u in plan['단위']:
        if u['id'] in 붙임앞 | 붙임뒤:
            if not u.get('새음성'): sys.exit(f'{u["id"]}: 바꿈 전이다 — 먼저 쉼넣기.py 바꿈')
            u['붙임'] = '앞' if u['id'] in 붙임앞 else '뒤'; n += 1
    PLAN.write_text(json.dumps(plan, ensure_ascii=False, indent=1) + '\n', encoding='utf-8', newline='\n')
