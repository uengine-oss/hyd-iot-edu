    cur = {c['id']: c['text'] for c in cues['cues']}
    old = {c['id']: c['text'] for c in json.loads(OLD.read_text(encoding='utf-8'))['cues']}
    for k in 새글:
        if k not in cur: sys.exit(f'바꿈용 큐에 없는 id {k}')
