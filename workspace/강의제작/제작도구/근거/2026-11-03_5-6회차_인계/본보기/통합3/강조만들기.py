def spoken(block):
    t = re.sub(r"^---\s*$|^>.*$|^\|.*$", "", block, flags=re.M).replace("**", "")
    return re.sub(r"\n{3,}", "\n\n", t).strip()


BLOCK = {}
for f in sorted(SD.glob('*.md')):
    p = re.split(r"^## \[SLIDE ([0-9~]+)\].*$", f.read_text(encoding='utf8'), flags=re.M)
    for i in range(1, len(p), 2):
        a = p[i].split('~'); t = spoken(re.split(r"^#{1,2} ", p[i + 1], flags=re.M)[0])
        for n in range(int(a[0]), int(a[-1]) + 1): BLOCK[n] = (f.name[:2], t)


def sents(n):
    return [s.strip() for s in re.split(r"(?<=[.?!])\s+|\n", BLOCK[n][1]) if s.strip()]


ERR = []


def box(n, q, hit=0, pad=(10, 4)):
    """글 q(문자열 또는 묶음)의 위치 → (중심, 반지름)."""
    qs = q if isinstance(q, tuple) else (q,)
    rs = []
    for one in qs:
        fr = doc[n - 1].search_for(one)
        if not fr:
            ERR.append(f'{n}장: 화면에서 「{one}」을 못 찾음'); return [960, 540], [50, 30]
        if isinstance(hit, tuple):
            rs += fr[hit[0]:hit[1]]
        else:
            if hit >= len(fr):
                ERR.append(f'{n}장: 「{one}」 {hit}번째 없음({len(fr)}개)'); return [960, 540], [50, 30]
            rs.append(fr[hit])
    x0, y0 = min(r.x0 for r in rs), min(r.y0 for r in rs); x1, y1 = max(r.x1 for r in rs), max(r.y1 for r in rs)
    return [round((x0 + x1) * K / 2), round((y0 + y1) * K / 2)], [round((x1 - x0) * K / 2 + pad[0] * K), round((y1 - y0) * K / 2 + pad[1] * K)]


def px(cx, cy, rx, ry):
    """80dpi 렌더에서 잰 도형 자리(픽셀) → 1920 좌표."""
    return ([round(cx * P), round(cy * P)], [round(rx * P), round(ry * P)])


