def digest(folder):
    h = hashlib.sha256()
    for p in sorted(folder.rglob('*')):
        if p.is_file() and '__pycache__' not in p.parts:
            h.update(p.relative_to(folder).as_posix().encode() + b'\0' + p.read_bytes())
    return h.hexdigest()


