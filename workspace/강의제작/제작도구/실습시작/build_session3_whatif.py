def integrated_lab():
    folder = OUT/'통합반/실습/03회차/랩'/NAME
    shot = Shots(folder)
    intro, sections = integrated_sections(shot)
    shot.report()
    if shot.missing:
        raise SystemExit('미촬영 사진이 남아 가이드를 쓰지 않았다 — 촬영/포털/사진_조치결과비교.py로 새 영상에서 뽑는다(가이드 P-8)')
    # 도구 실습(P-2 · P-13): 포털 화면에서 시작해 그 화면에서 끝나므로 옛 판의 VS Code 기록 랩 파일을 두지 않는다.
    for filename in ('AGENTS.md', 'CLAUDE.md', '.github/copilot-instructions.md', 'START.md', '준비_안내.md', 'kpi.csv', '비교_기록.md',
                     '결과/README.md', 'guide.html', '안내.html'):
        (folder/filename).unlink(missing_ok=True)
    for sub in ('.github', '결과'):
        old = folder/sub
        if old.is_dir():
            if any(old.iterdir()):
                raise SystemExit(f'{old}: 파일이 든 폴더 — 지우지 않고 멈춘다')
            old.rmdir()
    write(folder/'가이드.html', page(INTEGRATED_TITLE, intro, sections).replace('</html>', '</body></html>'))
    target = pack_page(folder)   # 옆의 옛 ZIP은 pack_page가 지운다
    register([], drop=['integrated-03-whatif'])
    print(f'{target.name}: {target.stat().st_size/1e6:.1f}MB')


integrated_lab()
