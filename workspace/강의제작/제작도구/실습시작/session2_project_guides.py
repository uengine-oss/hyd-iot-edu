def plan(goal, situation, steps, ai=True):
    """단계 머리 — 목표 · 상황 · 「뭐부터 해야 할까?」를 칸으로 나눠 보인다(한 문단에 섞지 않는다).
    상황은 지금 있는 것과 앞 단계까지 안 것이고, 처음 나오는 파일은 무엇인지 한 마디로 짚는다. 「뭐부터 해야 할까?」는 쉬운 말과 이론 이름으로 쓴 차례 목록이고,
    그대로 보내면 되는 부탁 글과 코드 이름은 정답 보기에만 둔다(가이드 P-3 · P-4 · P-5 · P-9 — 사용자 2026-11-20 「지금 현재 목표 이렇고 상황 이렇고 힌트 이렇게 …」 ·
    「그그냥 각 파일별로 어떠파일인지 설명 … 지금 목표강 ㅣ렇고 이런상황이다 뭐부터해야할까 라면서..」 · 「말을 좀 더 쉽게 … 다듬어줄 수 없나요??」)."""
    def items(xs, tag='ul'):   # 항목은 글 또는 (글, [아래 항목])
        return (f'<{tag}>' + ''.join(f'<li>{F.inline(x[0])}{items(x[1])}</li>' if isinstance(x, tuple) else f'<li>{F.inline(x)}</li>' for x in xs)
                + f'</{tag}>')
    return (f'<p><b>목표</b> {F.inline(goal)}</p><p><b>상황</b></p>{items(situation)}'
            f'<div class="hint{" ai" if ai else ""}"><p class="kind">뭐부터 해야 할까?</p>{items(steps, "ol")}</div>')


