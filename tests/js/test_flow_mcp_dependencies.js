const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const source = fs.readFileSync('it/portal/www/flows.js', 'utf8');
const start = source.indexOf('  function dependencyLine(item)');
const end = source.indexOf('  function collect()', start);
assert(start > 0 && end > start);
const context = {h: x => String(x ?? '').replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;'), problemsBlock: () => 'STRUCTURE_ERRORS'};
vm.createContext(context);
vm.runInContext(source.slice(start, end) + '\nthis.renderResult = resultBlock;', context);
const diagnostic = {attention_count: 1, note: '현재 인증은 호출할 때 다시 검사합니다.', items: [{node_name: '<script>task</script>', reason: '연결 서버가 등록되어 있지 않습니다.'}]};
const output = context.renderResult({ok: true, dependencies: diagnostic});
assert(output.includes('구조 검사 통과'));
assert(output.includes('외부 도구 연결 성공을 뜻하지 않습니다'));
assert(output.includes('연결 도구 준비가 필요한 단계 1개'));
assert(output.includes('연결 서버가 등록되어 있지 않습니다'));
assert(!output.includes('<script>'));
assert(context.renderResult({ok: false, dependencies: diagnostic}).includes('STRUCTURE_ERRORS'));
assert(!context.renderResult({ok: true}).includes('준비가 필요한 단계'));
assert(source.includes('detail += dependencyLine(dependency)'));
assert(source.includes('data-start="${h(id)}"'));
console.log('Flow dependency diagnostics: structure result, warnings, task detail and escaping PASS');
